// main/modules/compliance/contract/endpoints.ts
import { emptyBodySchema, endpoint } from '@bslt/contract';

import { complianceErrors } from './errors';
import {
  acceptTosBodySchema,
  acceptTosResponseSchema,
  ageAssuranceStatusResponseSchema,
  complianceIdParamsSchema,
  complianceUserIdParamsSchema,
  consentPreferencesPayloadSchema,
  consentPreferencesUpdateResponseSchema,
  dataExportDownloadResponseSchema,
  dataExportRequestResponseSchema,
  eraseUserResponseSchema,
  jurisdictionRuleResponseSchema,
  legalDocumentResponseSchema,
  legalDocumentsResponseSchema,
  legalHoldResponseSchema,
  listLegalHoldsQuerySchema,
  listLegalHoldsResponseSchema,
  placeLegalHoldBodySchema,
  publishLegalDocumentBodySchema,
  requestDataExportBodySchema,
  startAgeAssuranceBodySchema,
  startAgeAssuranceResponseSchema,
  tosStatusResponseSchema,
  updateConsentPreferencesBodySchema,
  upsertJurisdictionRuleBodySchema,
  userAgreementsResponseSchema,
} from './schemas';

export const complianceEndpoints = {
  getTosStatus: endpoint({
    method: 'GET',
    path: '/api/auth/tos/status',
    auth: 'user',
    response: tosStatusResponseSchema,
    summary: 'Get whether the authenticated user has accepted the latest Terms of Service',
  }),
  acceptTos: endpoint({
    method: 'POST',
    path: '/api/auth/tos/accept',
    auth: 'user',
    body: acceptTosBodySchema,
    response: acceptTosResponseSchema,
    errors: [complianceErrors.DOCUMENT_NOT_FOUND],
    invalidates: ['getTosStatus', 'getUserAgreements'],
    summary: 'Record acceptance of a Terms of Service document version',
  }),
  getCurrentLegal: endpoint({
    method: 'GET',
    path: '/api/legal/current',
    auth: 'public',
    cache: { public: 60 },
    response: legalDocumentsResponseSchema,
    summary: 'Get current legal documents',
  }),
  getUserAgreements: endpoint({
    method: 'GET',
    path: '/api/users/me/agreements',
    auth: 'user',
    requires: ['tos.accepted'],
    response: userAgreementsResponseSchema,
    summary: 'Get legal agreements for the authenticated user',
  }),
  publishLegal: endpoint({
    method: 'POST',
    path: '/api/admin/legal/publish',
    auth: 'admin',
    requires: ['tos.accepted'],
    body: publishLegalDocumentBodySchema,
    response: legalDocumentResponseSchema,
    errors: [complianceErrors.DOCUMENT_TYPE_INVALID],
    invalidates: ['getCurrentLegal'],
    summary: 'Publish a legal document version',
  }),
  getConsentPreferences: endpoint({
    method: 'GET',
    path: '/api/users/me/consent',
    auth: 'user',
    requires: ['tos.accepted'],
    response: consentPreferencesPayloadSchema,
    summary: 'Get current user consent preferences',
  }),
  updateConsentPreferences: endpoint({
    method: 'PATCH',
    path: '/api/users/me/consent/update',
    auth: 'user',
    requires: ['tos.accepted'],
    body: updateConsentPreferencesBodySchema,
    response: consentPreferencesUpdateResponseSchema,
    errors: [complianceErrors.CONSENT_PREFERENCES_REQUIRED],
    invalidates: ['getConsentPreferences'],
    summary: 'Update user consent preferences',
  }),
  requestDataExport: endpoint({
    method: 'POST',
    path: '/api/users/me/export',
    auth: 'user',
    requires: ['tos.accepted'],
    body: requestDataExportBodySchema,
    response: dataExportRequestResponseSchema,
    errors: [complianceErrors.DATA_EXPORT_ALREADY_PENDING],
    summary: 'Request a GDPR data export',
  }),
  getDataExportStatus: endpoint({
    method: 'GET',
    path: '/api/users/me/export/:id/status',
    auth: 'user',
    requires: ['tos.accepted'],
    params: complianceIdParamsSchema,
    response: dataExportRequestResponseSchema,
    errors: [complianceErrors.DATA_EXPORT_NOT_FOUND],
    summary: 'Check data export request status',
  }),
  downloadDataExport: endpoint({
    method: 'GET',
    path: '/api/users/me/export/:id/download',
    auth: 'user',
    requires: ['tos.accepted'],
    params: complianceIdParamsSchema,
    response: dataExportDownloadResponseSchema,
    errors: [
      complianceErrors.DATA_EXPORT_NOT_FOUND,
      complianceErrors.DATA_EXPORT_NOT_READY,
      complianceErrors.DATA_EXPORT_EXPIRED,
    ],
    summary: 'Download a completed data export',
  }),
  startAgeAssurance: endpoint({
    method: 'POST',
    path: '/api/compliance/age-assurance/check',
    auth: 'user',
    body: startAgeAssuranceBodySchema,
    response: startAgeAssuranceResponseSchema,
    errors: [
      complianceErrors.AGE_ASSURANCE_ATTESTATION_REQUIRED,
      complianceErrors.JURISDICTION_UNAVAILABLE,
    ],
    invalidates: ['getAgeAssuranceStatus'],
    summary: 'Perform an age-assurance check and record its outcome',
  }),
  getAgeAssuranceStatus: endpoint({
    method: 'GET',
    path: '/api/compliance/age-assurance/status',
    auth: 'user',
    response: ageAssuranceStatusResponseSchema,
    summary: 'Get age-assurance status and jurisdiction eligibility for the current viewer',
  }),
  placeLegalHold: endpoint({
    method: 'POST',
    path: '/api/admin/compliance/holds',
    auth: 'admin',
    requires: ['tos.accepted'],
    body: placeLegalHoldBodySchema,
    response: legalHoldResponseSchema,
    invalidates: ['listLegalHolds'],
    summary: 'Place a legal hold on a subject to prevent retention purge or erasure',
  }),
  listLegalHolds: endpoint({
    method: 'GET',
    path: '/api/admin/compliance/holds',
    auth: 'admin',
    requires: ['tos.accepted'],
    query: listLegalHoldsQuerySchema,
    response: listLegalHoldsResponseSchema,
    summary: 'List legal holds',
  }),
  releaseLegalHold: endpoint({
    method: 'POST',
    path: '/api/admin/compliance/holds/:id/release',
    auth: 'admin',
    requires: ['tos.accepted'],
    params: complianceIdParamsSchema,
    body: emptyBodySchema,
    response: legalHoldResponseSchema,
    errors: [complianceErrors.LEGAL_HOLD_NOT_FOUND, complianceErrors.LEGAL_HOLD_ALREADY_RELEASED],
    invalidates: ['listLegalHolds'],
    summary: 'Release an active legal hold',
  }),
  upsertJurisdictionRule: endpoint({
    method: 'POST',
    path: '/api/admin/compliance/jurisdictions',
    auth: 'admin',
    requires: ['tos.accepted'],
    body: upsertJurisdictionRuleBodySchema,
    response: jurisdictionRuleResponseSchema,
    summary: 'Create or update per-jurisdiction age and availability rules',
  }),
  eraseUserData: endpoint({
    method: 'POST',
    path: '/api/admin/compliance/users/:userId/erase',
    auth: 'admin',
    requires: ['tos.accepted'],
    params: complianceUserIdParamsSchema,
    body: emptyBodySchema,
    response: eraseUserResponseSchema,
    errors: [complianceErrors.LEGAL_HOLD_ACTIVE],
    summary: 'Orchestrate GDPR erasure across all modules implementing the privacy slot',
  }),
} as const;
