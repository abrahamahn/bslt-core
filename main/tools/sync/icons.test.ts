// main/tools/sync/icons.test.ts
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import { afterEach, describe, expect, it } from 'vitest';

import { run, syncIcons } from './icons';

const tempDirs: string[] = [];

function createTempRoot(): string {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'bslt-sync-icons-'));
  tempDirs.push(root);
  fs.mkdirSync(path.join(root, 'main/kernel/ui/icons'), { recursive: true });
  fs.mkdirSync(path.join(root, 'main/kernel/ui/src'), { recursive: true });
  return root;
}

afterEach(() => {
  while (tempDirs.length > 0) {
    const dir = tempDirs.pop();
    if (dir !== undefined) {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  }
});

describe('bslt sync icons', () => {
  it('throws when main/kernel/ui/icons contains zero .svg files', async () => {
    const root = createTempRoot();
    await expect(syncIcons({ root })).rejects.toThrow(/no \.svg icon files/iu);
  });

  it('throws when an icon filename is not kebab-case', async () => {
    const root = createTempRoot();
    fs.writeFileSync(
      path.join(root, 'main/kernel/ui/icons/BadName.svg'),
      '<svg viewBox="0 0 24 24"><path d="M0 0h24v24H0z"/></svg>\n',
      'utf8',
    );
    await expect(syncIcons({ root })).rejects.toThrow(/kebab-case/iu);
  });

  it('throws when an svg contains disallowed elements or event attributes', async () => {
    const root = createTempRoot();
    fs.writeFileSync(
      path.join(root, 'main/kernel/ui/icons/evil.svg'),
      '<svg viewBox="0 0 24 24"><script>alert(1)</script></svg>\n',
      'utf8',
    );
    await expect(syncIcons({ root })).rejects.toThrow(/unsupported svg element/iu);
  });

  it('fails check when icons.generated.ts is missing or stale and passes after syncIcons', async () => {
    const root = createTempRoot();
    fs.writeFileSync(
      path.join(root, 'main/kernel/ui/icons/close.svg'),
      '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><line x1="18" y1="6" x2="6" y2="18"/><line x1="6" y1="6" x2="18" y2="18"/></svg>\n',
      'utf8',
    );

    const missingResult = await run({ root });
    expect(missingResult.ok).toBe(false);

    const written = await syncIcons({ root });
    expect(written.changed).toBe(true);
    const content = fs.readFileSync(
      path.join(root, 'main/kernel/ui/src/icons.generated.ts'),
      'utf8',
    );
    expect(content).toContain(
      '// @generated by bslt sync icons from main/kernel/ui/icons/*.svg. Do not edit.',
    );
    expect(content).toContain('// <- main/kernel/ui/icons/close.svg');

    const okResult = await run({ root });
    expect(okResult.ok).toBe(true);
  });
});
