// main/tools/sync/stories.test.ts
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import { afterEach, describe, expect, it } from 'vitest';

import { run, syncStories } from './stories';

const tempDirs: string[] = [];

function createTempRoot(uiSource: string, catalogSource: string): string {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'bslt-sync-stories-'));
  tempDirs.push(root);
  fs.mkdirSync(path.join(root, 'main/kernel/ui/src'), { recursive: true });
  fs.mkdirSync(path.join(root, 'main/modules/devtools/web'), { recursive: true });
  fs.writeFileSync(path.join(root, 'main/kernel/ui/src/index.ts'), uiSource, 'utf8');
  fs.writeFileSync(path.join(root, 'main/modules/devtools/web/catalog.tsx'), catalogSource, 'utf8');
  return root;
}

afterEach(() => {
  while (tempDirs.length > 0) {
    const dir = tempDirs.pop();
    if (dir !== undefined) {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  }
});

describe('bslt sync stories', () => {
  it('throws when an exported @bslt/ui component is missing a story in catalog.tsx', async () => {
    const root = createTempRoot(
      `export { Alert, Button } from './elements';\nexport { ICON_SPRITE, useTheme } from './theme';\n`,
      `export const componentCatalog = {
  button: {
    id: 'button',
    name: 'Button',
    category: 'elements',
    description: 'Button story',
    variants: [{ name: 'Primary', description: 'Primary', code: '<Button />', render: () => null }],
  },
};\n`,
    );

    await expect(syncStories({ root })).rejects.toThrow(/missing story.*Alert/iu);
  });

  it('throws when a story has duplicate variant names or mismatched id', async () => {
    const root = createTempRoot(
      `export { Button } from './elements';\n`,
      `export const componentCatalog = {
  button: {
    id: 'button',
    name: 'Button',
    category: 'elements',
    description: 'Button story',
    variants: [
      { name: 'Primary', description: 'One', code: '<Button />', render: () => null },
      { name: 'Primary', description: 'Duplicate', code: '<Button />', render: () => null },
    ],
  },
};\n`,
    );

    await expect(syncStories({ root })).rejects.toThrow(/duplicate variant name/iu);
  });

  it('throws when a story declares zero variants', async () => {
    const root = createTempRoot(
      `export { Button } from './elements';\n`,
      `export const componentCatalog = {
  button: {
    id: 'button',
    name: 'Button',
    category: 'elements',
    description: 'Button story',
    variants: [],
  },
};\n`,
    );

    await expect(syncStories({ root })).rejects.toThrow(/at least one variant/iu);
  });

  it('fails check when story-index.generated.ts is missing or stale and passes after syncStories', async () => {
    const root = createTempRoot(
      `export { Alert, Button } from './elements';\nexport { ICON_SPRITE, THEME_STORAGE_KEYS, cn } from './utils';\nexport type { IconName } from './icons.generated';\n`,
      `export const componentCatalog = {
  alert: {
    id: 'alert',
    name: 'Alert',
    category: 'elements',
    description: 'Alert story',
    variants: [{ name: 'Info', description: 'Info', code: '<Alert />', render: () => null }],
  },
  button: {
    id: 'button',
    name: 'Button',
    category: 'elements',
    description: 'Button story',
    variants: [{ name: 'Primary', description: 'Primary', code: '<Button />', render: () => null }],
  },
};\n`,
    );

    const missingResult = await run({ root });
    expect(missingResult.ok).toBe(false);

    const synced = await syncStories({ root });
    expect(synced.changed).toBe(true);
    expect(synced.count).toBe(2);

    const generated = fs.readFileSync(
      path.join(root, 'main/modules/devtools/web/generated/story-index.generated.ts'),
      'utf8',
    );
    expect(generated).toContain('// @generated by bslt sync stories');
    expect(generated).toContain("storyId: 'alert'");
    expect(generated).toContain("component: 'Button'");

    const okResult = await run({ root });
    expect(okResult.ok).toBe(true);
  });
});
