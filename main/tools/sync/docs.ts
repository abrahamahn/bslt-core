function collectPageComponentToModule(
  root: string,
  moduleIds: readonly string[],
): Map<string, string> {
  const map = new Map<string, string>();
  for (const modId of moduleIds) {
    const webDir = path.join(root, 'main/modules', modId, 'web');
    if (!existsSync(webDir)) continue;
    const walk = (dir: string): void => {
      for (const entry of readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) {
          if (entry.name !== 'node_modules' && entry.name !== 'dist') walk(full);
        } else if (
          entry.isFile() &&
          (entry.name.endsWith('.tsx') || entry.name.endsWith('.ts')) &&
          !entry.name.includes('.test.')
        ) {
          const text = readFileSync(full, 'utf8');
          for (const m of text.matchAll(/export\s+(?:function|const)\s+([A-Z][A-Za-z0-9_]*)/gu)) {
            if (m[1] !== undefined) map.set(m[1], modId);
          }
        }
      }
    };
    walk(webDir);
  }
  return map;
}

function attributeWebPath(
  routePath: string,
  pageName: string | null,
  pageMap: ReadonlyMap<string, string>,
  knownModules: ReadonlySet<string>,
): string {
  if (pageName !== null) {
    const byPage = pageMap.get(pageName);
    if (byPage !== undefined) return byPage;
  }
  const clean = routePath.replace(/^\/+/u, '');
  const seg = clean.split('/')[0] ?? '';
  const pathToModule: Readonly<Record<string, string>> = {
    login: 'identity',
    register: 'identity',
    'forgot-password': 'identity',
    'reset-password': 'identity',
    'verify-email': 'identity',
    'confirm-email-change': 'identity',
    'magic-link': 'identity',
    profile: 'identity',
    organization: 'orgs',
    invitations: 'orgs',
    pricing: 'billing',
    billing: 'billing',
    checkout: 'billing',
    tasks: 'tasks',
    files: 'files',
    activities: 'audit',
    notifications: 'notifications',
    unsubscribe: 'notifications',
    support: 'support',
    status: 'status',
    search: 'search',
    report: 'moderation',
    moderation: 'moderation',
    terms: 'compliance',
    privacy: 'compliance',
    cookies: 'compliance',
    'acceptable-use': 'compliance',
    disclaimer: 'compliance',
    dmca: 'compliance',
    'ui-library': 'devtools',
    'side-peek-ui-library': 'devtools',
    developer: 'devtools',
  };
  if (seg === 'admin') {
    const sub = clean.split('/')[1] ?? '';
    const adminSubToModule: Readonly<Record<string, string>> = {
      users: 'admin',
      tenants: 'orgs',
      security: 'audit',
      audit: 'audit',
      support: 'support',
      moderation: 'moderation',
      'feature-flags': 'flags',
      'webhook-monitor': 'webhooks',
      webhooks: 'webhooks',
      jobs: 'admin',
      billing: 'billing',
      legal: 'compliance',
      notifications: 'notifications',
      routes: 'devtools',
      dashboard: 'admin',
      health: 'admin',
    };
    const adminMod = adminSubToModule[sub];
    if (adminMod !== undefined && knownModules.has(adminMod)) {
      return adminMod;
    }
    return knownModules.has('admin') ? 'admin' : 'kernel';
  }
  const mapped = pathToModule[seg];
  if (mapped !== undefined && knownModules.has(mapped)) {
    return mapped;
  }
  return 'kernel';
}

function collectCronEntries(root: string, moduleIds: readonly string[]): CronEntrySummary[] {
  const entries: CronEntrySummary[] = [
    {
      owner: 'kernel',
      name: 'sys.outbox.retention',
      schedule: '0 2 * * *',
      sourceFile: 'main/kernel/server/src/cron/kernel-crons.ts',
    },
    {
      owner: 'kernel',
      name: 'sys.jobs.retention',
      schedule: '10 2 * * *',
      sourceFile: 'main/kernel/server/src/cron/kernel-crons.ts',
    },
    {
      owner: 'kernel',
      name: 'sys.jobs.dead_metrics',
      schedule: '* * * * *',
      sourceFile: 'main/kernel/server/src/cron/kernel-crons.ts',
    },
  ];

  for (const modId of moduleIds) {
    const serverDir = path.join(root, 'main/modules', modId, 'server');
    if (!existsSync(serverDir)) continue;
    const files = readdirSync(serverDir, { withFileTypes: true })
      .filter((e) => e.isFile() && e.name.endsWith('.ts') && !e.name.includes('.test.'))
      .map((e) => path.join(serverDir, e.name))
      .sort();

    for (const absFile of files) {
      const src = readFileSync(absFile, 'utf8');
      if (!src.includes('cron')) continue;
      const sf = ts.createSourceFile(absFile, src, ts.ScriptTarget.ESNext, true);
      const relFile = path.relative(root, absFile).split(path.sep).join('/');

      const visit = (node: ts.Node): void => {
        if (
          ts.isPropertyAssignment(node) &&
          (ts.isIdentifier(node.name) || ts.isStringLiteral(node.name)) &&
          node.name.text === 'cron' &&
          ts.isObjectLiteralExpression(node.initializer)
        ) {
          for (const prop of node.initializer.properties) {
            if (!ts.isPropertyAssignment(prop)) continue;
            const cronKey =
              ts.isIdentifier(prop.name) || ts.isStringLiteral(prop.name) ? prop.name.text : '';
            if (cronKey === '' || !ts.isObjectLiteralExpression(prop.initializer)) continue;
            let schedule = 'custom';
            for (const sub of prop.initializer.properties) {
              if (
                ts.isPropertyAssignment(sub) &&
                (ts.isIdentifier(sub.name) || ts.isStringLiteral(sub.name)) &&
                (sub.name.text === 'schedule' || sub.name.text === 'every') &&
                ts.isStringLiteral(sub.initializer)
              ) {
                schedule = sub.initializer.text;
              }
            }
            entries.push({
              owner: modId,
              name: `${modId}.${cronKey}`,
              schedule,
              sourceFile: relFile,
            });
          }
        }
        ts.forEachChild(node, visit);
      };
      visit(sf);
    }
  }

  return entries.sort((a, b) =>
    a.owner === b.owner ? compareText(a.name, b.name) : compareText(a.owner, b.owner),
  );
}

function renderApiReference(
  workspace: ParsedModulesWorkspace,
  apiSurface: ApiSurfaceSnapshot,
): string {
  const allModuleIds = [...workspace.installedIds, ...workspace.devOnlyIds];
  const knownModules = new Set(allModuleIds);

  const KERNEL_ROUTE_TAGS = new Set(['kernel', 'system', 'realtime']);
  const routeRows: string[] = [];
  for (const route of apiSurface.routes) {
    const rawModule =
      route.module !== undefined && route.module !== null && route.module !== ''
        ? route.module
        : 'kernel';
    const owner = KERNEL_ROUTE_TAGS.has(rawModule) ? 'kernel' : rawModule;
    if (owner !== 'kernel' && !knownModules.has(owner)) {
      throw new Error(
        `Unattributed HTTP route ${route.method} ${route.path}: unknown owner "${rawModule}"`,
      );
    }
    const endpointLabel = route.contract?.endpoint ?? 'system';
    routeRows.push(
      `| \`${route.method}\` | \`${route.path}\` | \`${owner}\` | \`${route.auth}\` | \`${endpointLabel}\` |`,
    );
  }

  const moduleSections: string[] = [];
  for (const modId of allModuleIds) {
    const mod = workspace.modules.get(modId);
    if (mod === undefined || mod.endpoints.length === 0) continue;
    const epLines = mod.endpoints.map(
      (ep) =>
        `| \`${ep.key}\` | \`${ep.method}\` | \`${ep.path}\` | \`${ep.auth}\` | ${ep.summary || '—'} |`,
    );
    moduleSections.push(
      [
        `### \`@bslt/${mod.id}\` (${String(mod.endpoints.length)} endpoints)`,
        '',
        `<!-- <- main/modules/${mod.id}/contract/endpoints.ts -->`,
        '',
        mod.summary,
        '',
        '| Key | Method | Path | Auth | Summary |',
        '| --- | ------ | ---- | ---- | ------- |',
        ...epLines,
        '',
      ].join('\n'),
    );
  }

  return [
    GENERATED_BANNER(
      'bslt.config.ts, main/modules/*/contract/endpoints.ts, and main/tools/snapshots/api-surface.json',
    ),
    '',
    '# HTTP API Reference',
    '',
    `Every registered HTTP route (${String(apiSurface.routes.length)} total) is attributed to an installed module or \`kernel\`. Full JSON schemas live in [\`openapi.json\`](./openapi.json).`,
    '',
    '## Composed Route Inventory',
    '',
    '| Method | Path | Owner | Auth | Contract |',
    '| ------ | ---- | ----- | ---- | -------- |',
    ...routeRows,
    '',
    '## Module Endpoint Declarations',
    '',
    ...moduleSections,
  ].join('\n');
}

function renderDatabaseReference(root: string, knownModules: ReadonlySet<string>): string {
  const catalog = loadCatalog(root);
  const tableRows: string[] = [];

  for (const table of catalog.tables) {
    const owner = table.source;
    if (owner !== 'kernel' && !knownModules.has(owner)) {
      throw new Error(`Unattributed database table "${table.name}": unknown source "${owner}"`);
    }
    const rlsDesc = describeTableRls(table);
    const rlsClass = rlsDesc.rls?.class ?? 'unclassified';
    const ownerCol = rlsDesc.rls?.ownerColumn ?? '—';
    tableRows.push(
      `| \`${table.name}\` | \`${owner}\` | \`${rlsClass}\` | \`${ownerCol}\` | ${String(table.columns.length)} |`,
    );
  }

  const typeRows = catalog.types.map((t) => {
    const details =
      t.kind === 'enum' ? t.labels.map((l) => `\`${l}\``).join(', ') || '—' : (t.baseType ?? '—');
    return `| \`${t.name}\` | \`${t.source}\` | \`${t.kind}\` | ${details} |`;
  });

  const fnRows = catalog.functions.map((fn) => {
    const security = fn.securityDefiner ? 'definer' : 'invoker';
    return `| \`${fn.name}\` | \`${fn.source}\` | \`${security}\` | \`${fn.volatility}\` |`;
  });

  return [
    GENERATED_BANNER('main/kernel/db/catalog.snapshot.json'),
    '',
    '# Database Schema & RLS Reference',
    '',
    `Single \`public\` schema with ${String(catalog.tables.length)} attributed tables under forced Row-Level Security (\`sys_apply_rls\`).`,
    '',
    '## Tables',
    '',
    '| Table | Owner | RLS Class | Owner Column | Columns |',
    '| ----- | ----- | --------- | ------------ | ------- |',
    ...tableRows,
    '',
    '## Enum & Domain Types',
    '',
    '| Type | Owner | Kind | Values |',
    '| ---- | ----- | ---- | ------ |',
    ...typeRows,
    '',
    '## SQL Functions',
    '',
    '| Function | Owner | Security | Volatility |',
    '| -------- | ----- | -------- | ---------- |',
    ...fnRows,
    '',
  ].join('\n');
}

function renderEventsJobsCronReference(root: string, workspace: ParsedModulesWorkspace): string {
  const allModuleIds = [...workspace.installedIds, ...workspace.devOnlyIds];
  const eventRows: string[] = [];
  const jobRows: string[] = [
    '| `kernel` | `sys.outbox.retention` | `main/kernel/server/src/cron/kernel-crons.ts` |',
    '| `kernel` | `sys.jobs.retention` | `main/kernel/server/src/cron/kernel-crons.ts` |',
    '| `kernel` | `sys.jobs.dead_metrics` | `main/kernel/server/src/cron/kernel-crons.ts` |',
  ];

  for (const modId of allModuleIds) {
    const mod = workspace.modules.get(modId);
    if (mod === undefined) continue;
    for (const ev of mod.events) {
      eventRows.push(
        `| \`${mod.id}\` | \`${ev.name}\` | \`${ev.key}\` | ${ev.webhook ? 'yes' : 'no'} | \`main/modules/${mod.id}/contract/events.ts\` |`,
      );
    }
    for (const jobKey of mod.jobKeys) {
      jobRows.push(
        `| \`${mod.id}\` | \`${mod.id}.${jobKey}\` | \`main/modules/${mod.id}/module.ts\` |`,
      );
    }
  }

  const cronEntries = collectCronEntries(root, allModuleIds);
  const cronRows = cronEntries.map(
    (c) => `| \`${c.owner}\` | \`${c.name}\` | \`${c.schedule}\` | \`${c.sourceFile}\` |`,
  );

  return [
    GENERATED_BANNER(
      'bslt.config.ts, main/modules/*/module.ts, and main/kernel/server/src/cron/kernel-crons.ts',
    ),
    '',
    '# Events, Jobs & Cron Reference',
    '',
    'Every outbox event (`sys_outbox`), background job (`sys_jobs`), and scheduled cron entry attributed to its owning module or `kernel`.',
    '',
    '## Domain Events (`sys_outbox`)',
    '',
    '| Owner | Event Name | Manifest Key | Outbound Webhook | Source |',
    '| ----- | ---------- | ------------ | ---------------- | ------ |',
    ...eventRows,
    '',
    '## Background Jobs (`sys_jobs`)',
    '',
    '| Owner | Job Name | Source |',
    '| ----- | -------- | ------ |',
    ...jobRows,
    '',
    '## Scheduled Cron Entries (`sys_cron_schedules`)',
    '',
    '| Owner | Cron Name | Schedule | Source |',
    '| ----- | --------- | -------- | ------ |',
    ...cronRows,
    '',
  ].join('\n');
}

function renderWebRoutesReference(
  root: string,
  workspace: ParsedModulesWorkspace,
  webSnapshot: WebRoutesSnapshot,
): string {
  const allModuleIds = [...workspace.installedIds, ...workspace.devOnlyIds];
  const knownModules = new Set(allModuleIds);
  const pageMap = collectPageComponentToModule(root, allModuleIds);
  const allEnabled =
    webSnapshot.configurations.find((c) => c.name === 'all-enabled') ??
    webSnapshot.configurations[webSnapshot.configurations.length - 1];

  if (allEnabled === undefined) {
    throw new Error('web-routes.json contains no configurations');
  }

  const routeRows = allEnabled.routes.map((r) => {
    const owner = attributeWebPath(r.path, r.page, pageMap, knownModules);
    return `| \`${r.path}\` | \`${owner}\` | \`${r.page}\` | \`${r.guard}\` | ${r.layouts.map((l) => `\`${l}\``).join(', ') || '—'} |`;
  });

  const navItems = allEnabled.navigation?.primary?.['admin'] ?? [];
  const navRows = navItems.map((item) => {
    const owner = attributeWebPath(item.to, null, pageMap, knownModules);
    return `| ${item.label} | \`${item.to}\` | \`${owner}\` |`;
  });

  const footerRows = (allEnabled.navigation?.footer ?? []).flatMap((sec) =>
    sec.links.map((link) => {
      const owner = attributeWebPath(link.path, null, pageMap, knownModules);
      return `| ${sec.section} | ${link.title} | \`${link.path}\` | \`${owner}\` |`;
    }),
  );

  const adminRows = (allEnabled.admin ?? []).map((surface) => {
    const owner = attributeWebPath(surface.href, null, pageMap, knownModules);
    return `| \`${surface.id}\` | ${surface.label} | \`${surface.href}\` | \`${owner}\` | ${surface.inNavigation ? 'yes' : 'no'} |`;
  });

  return [
    GENERATED_BANNER('main/tools/snapshots/web-routes.json and main/modules/*/web'),
    '',
    '# Web Routes & Navigation Reference',
    '',
    `Every client/SSR route (${String(allEnabled.routes.length)}), navigation link, and admin console surface attributed to its owning module or \`kernel\`.`,
    '',
    '## Web Routes',
    '',
    '| Path | Owner | Component | Guard | Shells |',
    '| ---- | ----- | --------- | ----- | ------ |',
    ...routeRows,
    '',
    '## Primary Navigation',
    '',
    '| Label | Path | Owner |',
    '| ----- | ---- | ----- |',
    ...navRows,
    '',
    '## Public Footer Links',
    '',
    '| Section | Title | Path | Owner |',
    '| ------- | ----- | ---- | ----- |',
    ...footerRows,
    '',
    '## Console Admin Surfaces',
    '',
    '| Surface ID | Label | Path | Owner | In Nav |',
    '| ---------- | ----- | ---- | ----- | ------ |',
    ...adminRows,
    '',
  ].join('\n');
}

function renderModuleDagReference(workspace: ParsedModulesWorkspace): string {
  const allModuleIds = [...workspace.installedIds, ...workspace.devOnlyIds];
  const devSet = new Set(workspace.devOnlyIds);

  const mermaidLines: string[] = ['```mermaid', 'flowchart TD'];
  for (const modId of allModuleIds) {
    const mod = workspace.modules.get(modId);
    if (mod === undefined) continue;
    mermaidLines.push(`  ${mod.id}["@bslt/${mod.id}"]`);
    for (const dep of mod.dependsOn) {
      mermaidLines.push(`  ${mod.id} --> ${dep}`);
    }
  }
  mermaidLines.push('```');

  const summaryRows: string[] = [];
  for (const modId of allModuleIds) {
    const mod: ParsedModuleInfo | undefined = workspace.modules.get(modId);
    if (mod === undefined) continue;
    const scope = devSet.has(modId) ? 'devOnly' : 'installed';
    const deps = mod.dependsOn.length > 0 ? mod.dependsOn.map((d) => `\`${d}\``).join(', ') : '—';
    summaryRows.push(
      `| \`@bslt/${mod.id}\` | \`${scope}\` | \`${mod.status}\` | ${deps} | ${String(mod.endpoints.length)} | ${String(mod.tables.length)} | ${String(mod.events.length)} | ${String(mod.jobKeys.length)} |`,
    );
  }

  return [
    GENERATED_BANNER('bslt.config.ts and main/modules/*/module.ts'),
    '',
    '# Module Dependency Graph',
    '',
    'Strict acyclic dependency graph across all vertical modules registered in `bslt.config.ts` (`module-graph` gate).',
    '',
    '## Dependency DAG',
    '',
    ...mermaidLines,
    '',
    '## Module Inventory',
    '',
    '| Package | Scope | Status | `dependsOn` | Endpoints | Tables | Events | Jobs |',
    '| ------- | ----- | ------ | ----------- | --------- | ------ | ------ | ---- |',
    ...summaryRows,
    '',
  ].join('\n');
}

function renderDirectionStatusBlock(workspace: ParsedModulesWorkspace): string {
  const allModuleIds = [...workspace.installedIds, ...workspace.devOnlyIds];
  const devSet = new Set(workspace.devOnlyIds);
  const rows: string[] = [
    STATUS_START_MARKER,
    `<!-- @generated by ${SYNC_DOCS_COMMAND} from bslt.config.ts and main/modules/*/module.ts. Do not edit. -->`,
    '',
    '| Module | Scope | Status | Summary | Endpoints | Tables | Events | Jobs |',
    '| ------ | ----- | ------ | ------- | --------- | ------ | ------ | ---- |',
  ];
  for (const modId of allModuleIds) {
    const mod = workspace.modules.get(modId);
    if (mod === undefined) continue;
    const scope = devSet.has(modId) ? 'devOnly' : 'installed';
    rows.push(
      `| \`${mod.id}\` | \`${scope}\` | \`${mod.status}\` | ${mod.summary} | ${String(mod.endpoints.length)} | ${String(mod.tables.length)} | ${String(mod.events.length)} | ${String(mod.jobKeys.length)} |`,
    );
  }
  rows.push('', STATUS_END_MARKER);
  return rows.join('\n');
}

function updateDirectionWithStatusBlock(existingText: string, statusBlock: string): string {
  const startIdx = existingText.indexOf(STATUS_START_MARKER);
  const endIdx = existingText.indexOf(STATUS_END_MARKER);
  if (startIdx === -1 || endIdx === -1 || endIdx < startIdx) {
    return existingText;
  }
  return (
    existingText.slice(0, startIdx) +
    statusBlock +
    existingText.slice(endIdx + STATUS_END_MARKER.length)
  );
}

function renderWebDocsReferenceModule(
  root: string,
  workspace: ParsedModulesWorkspace,
  apiSurface: ApiSurfaceSnapshot,
  webSnapshot: WebRoutesSnapshot,
): string {
  const allModuleIds = [...workspace.installedIds, ...workspace.devOnlyIds];
  const knownModules = new Set(allModuleIds);
  const devSet = new Set(workspace.devOnlyIds);
  const kernelTags = new Set(['kernel', 'system', 'realtime']);

  // Build endpoint summary lookup from contract/endpoints.ts declarations
  const summaryByContract = new Map<string, string>();
  const summaryByMethodPath = new Map<string, string>();
  for (const modId of allModuleIds) {
    const mod = workspace.modules.get(modId);
    if (mod === undefined) continue;
    for (const ep of mod.endpoints) {
      if (ep.summary !== '') {
        summaryByContract.set(`${mod.id}.${ep.key}`, ep.summary);
        summaryByMethodPath.set(`${ep.method.toUpperCase()} ${ep.path}`, ep.summary);
      }
    }
  }

  const apiRoutes = apiSurface.routes.map((route) => {
    const rawModule =
      route.module !== undefined && route.module !== null && route.module !== ''
        ? route.module
        : 'kernel';
    const owner = kernelTags.has(rawModule) ? 'kernel' : rawModule;
    if (owner !== 'kernel' && !knownModules.has(owner)) {
      throw new Error(
        `Unattributed HTTP route ${route.method} ${route.path}: unknown owner "${rawModule}"`,
      );
    }
    const contractEndpoint = route.contract?.endpoint ?? 'system';
    const summary =
      summaryByContract.get(contractEndpoint) ??
      summaryByMethodPath.get(`${route.method.toUpperCase()} ${route.path}`) ??
      '';
    const responseEntries = Object.entries(route.contract?.responses ?? {})
      .sort(([a], [b]) => compareText(a, b))
      .map(([status, schema]) => `${status}:${schema}`);
    return {
      method: route.method,
      path: route.path,
      owner,
      auth: route.auth,
      roles: [...(route.roles ?? [])],
      contract: contractEndpoint,
      summary,
      body: route.contract?.body ?? null,
      query: route.contract?.query ?? null,
      pathParams: route.contract?.pathParams ?? null,
      responses: responseEntries,
    };
  });

  const pageMap = collectPageComponentToModule(root, allModuleIds);
  const allEnabled =
    webSnapshot.configurations.find((c) => c.name === 'all-enabled') ??
    webSnapshot.configurations[webSnapshot.configurations.length - 1];
  if (allEnabled === undefined) {
    throw new Error('web-routes.json contains no configurations');
  }

  const webRoutes = allEnabled.routes.map((route) => ({
    path: route.path,
    owner: attributeWebPath(route.path, route.page, pageMap, knownModules),
    page: route.page,
    guard: route.guard,
    layouts: [...route.layouts],
    adminSurface: route.adminSurface,
  }));

  const adminSurfaces = (allEnabled.admin ?? []).map((surface) => ({
    id: surface.id,
    label: surface.label,
    href: surface.href,
    owner: attributeWebPath(surface.href, null, pageMap, knownModules),
    inNavigation: surface.inNavigation,
  }));

  const catalog = loadCatalog(root);
  const dbTables = catalog.tables.map((table) => {
    const owner = table.source;
    if (owner !== 'kernel' && !knownModules.has(owner)) {
      throw new Error(`Unattributed database table "${table.name}": unknown source "${owner}"`);
    }
    const rlsDesc = describeTableRls(table);
    return {
      name: table.name,
      owner,
      rlsClass: rlsDesc.rls?.class ?? 'unclassified',
      ownerColumn: rlsDesc.rls?.ownerColumn ?? null,
      columnCount: table.columns.length,
    };
  });

  const dbTypes = catalog.types.map((t) => ({
    name: t.name,
    owner: t.source,
    kind: t.kind,
    details: t.kind === 'enum' ? t.labels.join(', ') : (t.baseType ?? ''),
  }));

  const dbFunctions = catalog.functions.map((fn) => ({
    name: fn.name,
    owner: fn.source,
    security: fn.securityDefiner ? ('definer' as const) : ('invoker' as const),
    volatility: fn.volatility,
  }));

  const events: Array<{
    readonly owner: string;
    readonly name: string;
    readonly key: string;
    readonly webhook: boolean;
  }> = [];
  const jobs: Array<{ readonly owner: string; readonly name: string }> = [
    { owner: 'kernel', name: 'sys.outbox.retention' },
    { owner: 'kernel', name: 'sys.jobs.retention' },
    { owner: 'kernel', name: 'sys.jobs.dead_metrics' },
  ];

  for (const modId of allModuleIds) {
    const mod = workspace.modules.get(modId);
    if (mod === undefined) continue;
    for (const ev of mod.events) {
      events.push({
        owner: mod.id,
        name: ev.name,
        key: ev.key,
        webhook: ev.webhook,
      });
    }
    for (const jobKey of mod.jobKeys) {
      jobs.push({
        owner: mod.id,
        name: `${mod.id}.${jobKey}`,
      });
    }
  }

  const crons = collectCronEntries(root, allModuleIds).map((c) => ({
    owner: c.owner,
    name: c.name,
    schedule: c.schedule,
  }));

  const apiCountByOwner = new Map<string, number>();
  for (const route of apiRoutes) {
    apiCountByOwner.set(route.owner, (apiCountByOwner.get(route.owner) ?? 0) + 1);
  }
  const webCountByOwner = new Map<string, number>();
  for (const route of webRoutes) {
    webCountByOwner.set(route.owner, (webCountByOwner.get(route.owner) ?? 0) + 1);
  }
  const tableCountByOwner = new Map<string, number>();
  for (const table of dbTables) {
    tableCountByOwner.set(table.owner, (tableCountByOwner.get(table.owner) ?? 0) + 1);
  }

  const modules = allModuleIds.flatMap((modId) => {
    const mod = workspace.modules.get(modId);
    if (mod === undefined) return [];
    return [
      {
        id: mod.id,
        scope: devSet.has(modId) ? ('devOnly' as const) : ('installed' as const),
        status: mod.status,
        summary: mod.summary,
        dependsOn: [...mod.dependsOn],
        endpointCount: apiCountByOwner.get(mod.id) ?? mod.endpoints.length,
        webRouteCount: webCountByOwner.get(mod.id) ?? 0,
        tableCount: tableCountByOwner.get(mod.id) ?? mod.tables.length,
        eventCount: mod.events.length,
        jobCount: mod.jobKeys.length,
      },
    ];
  });

  const payload = {
    modules,
    apiRoutes,
    webRoutes,
    adminSurfaces,
    dbTables,
    dbTypes,
    dbFunctions,
    events,
    jobs,
    crons,
  };

  const serializedJsonLiteral = JSON.stringify(JSON.stringify(payload));

  return [
    `// ${GENERATED_WEB_DOCS_REFERENCE}`,
    `// @generated by \`${SYNC_DOCS_COMMAND}\` from bslt.config.ts, snapshots, and catalog.snapshot.json. Do not edit.`,
    '',
    'export interface DocsApiEndpointRef {',
    '  readonly method: string;',
    '  readonly path: string;',
    '  readonly owner: string;',
    '  readonly auth: string;',
    '  readonly roles: readonly string[];',
    '  readonly contract: string;',
    '  readonly summary: string;',
    '  readonly body: string | null;',
    '  readonly query: string | null;',
    '  readonly pathParams: string | null;',
    '  readonly responses: readonly string[];',
    '}',
    '',
    'export interface DocsWebRouteRef {',
    '  readonly path: string;',
    '  readonly owner: string;',
    '  readonly page: string;',
    '  readonly guard: string;',
    '  readonly layouts: readonly string[];',
    '  readonly adminSurface: string | null;',
    '}',
    '',
    'interface DocsAdminSurfaceRef {',
    '  readonly id: string;',
    '  readonly label: string;',
    '  readonly href: string;',
    '  readonly owner: string;',
    '  readonly inNavigation: boolean;',
    '}',
    '',
    'export interface DocsModuleRef {',
    '  readonly id: string;',
    "  readonly scope: 'installed' | 'devOnly';",
    '  readonly status: string;',
    '  readonly summary: string;',
    '  readonly dependsOn: readonly string[];',
    '  readonly endpointCount: number;',
    '  readonly webRouteCount: number;',
    '  readonly tableCount: number;',
    '  readonly eventCount: number;',
    '  readonly jobCount: number;',
    '}',
    '',
    'interface DocsDbTableRef {',
    '  readonly name: string;',
    '  readonly owner: string;',
    '  readonly rlsClass: string;',
    '  readonly ownerColumn: string | null;',
    '  readonly columnCount: number;',
    '}',
    '',
    'interface DocsDbTypeRef {',
    '  readonly name: string;',
    '  readonly owner: string;',
    '  readonly kind: string;',
    '  readonly details: string;',
    '}',
    '',
    'interface DocsDbFunctionRef {',
    '  readonly name: string;',
    '  readonly owner: string;',
    "  readonly security: 'definer' | 'invoker';",
    '  readonly volatility: string;',
    '}',
    '',
    'interface DocsEventRef {',
    '  readonly owner: string;',
    '  readonly name: string;',
    '  readonly key: string;',
    '  readonly webhook: boolean;',
    '}',
    '',
    'interface DocsJobRef {',
    '  readonly owner: string;',
    '  readonly name: string;',
    '}',
    '',
    'interface DocsCronRef {',
    '  readonly owner: string;',
    '  readonly name: string;',
    '  readonly schedule: string;',
    '}',
    '',
    'interface DocsReferenceData {',
    '  readonly modules: readonly DocsModuleRef[];',
    '  readonly apiRoutes: readonly DocsApiEndpointRef[];',
    '  readonly webRoutes: readonly DocsWebRouteRef[];',
    '  readonly adminSurfaces: readonly DocsAdminSurfaceRef[];',
    '  readonly dbTables: readonly DocsDbTableRef[];',
    '  readonly dbTypes: readonly DocsDbTypeRef[];',
    '  readonly dbFunctions: readonly DocsDbFunctionRef[];',
    '  readonly events: readonly DocsEventRef[];',
    '  readonly jobs: readonly DocsJobRef[];',
    '  readonly crons: readonly DocsCronRef[];',
    '}',
    '',
    `const DOCS_REFERENCE_JSON = ${serializedJsonLiteral};`,
    '',
    'export const DOCS_REFERENCE: DocsReferenceData = JSON.parse(',
    '  DOCS_REFERENCE_JSON,',
    ') as DocsReferenceData;',
    '',
  ].join('\n');
}

export async function buildGeneratedDocsMap(
  root: string = REPO_ROOT,
): Promise<Map<string, string>> {
  const workspace = loadModulesWorkspace(root);
  const allModuleIds = [...workspace.installedIds, ...workspace.devOnlyIds];
  const knownModules = new Set(allModuleIds);

  const apiSurface = JSON.parse(
    readFileSync(path.join(root, 'main/tools/snapshots/api-surface.json'), 'utf8'),
  ) as ApiSurfaceSnapshot;
  const webRoutes = JSON.parse(
    readFileSync(path.join(root, 'main/tools/snapshots/web-routes.json'), 'utf8'),
  ) as WebRoutesSnapshot;

  const rawFiles = new Map<string, string>([
    ['docs/reference/api.md', renderApiReference(workspace, apiSurface)],
    ['docs/reference/database.md', renderDatabaseReference(root, knownModules)],
    ['docs/reference/events-jobs-cron.md', renderEventsJobsCronReference(root, workspace)],
    ['docs/reference/web-routes.md', renderWebRoutesReference(root, workspace, webRoutes)],
    ['docs/reference/module-dag.md', renderModuleDagReference(workspace)],
    [
      GENERATED_WEB_DOCS_REFERENCE,
      renderWebDocsReferenceModule(root, workspace, apiSurface, webRoutes),
    ],
  ]);

  const directionAbs = path.join(root, DIRECTION_DOC_REL);
  if (existsSync(directionAbs)) {
    const existingDirection = readFileSync(directionAbs, 'utf8');
    if (existingDirection.includes(STATUS_START_MARKER)) {
      rawFiles.set(
        DIRECTION_DOC_REL,
        updateDirectionWithStatusBlock(existingDirection, renderDirectionStatusBlock(workspace)),
      );
    }
  }

  const prettierConfigPath = path.join(root, 'config/.prettierrc');
  const prettierOptions = existsSync(prettierConfigPath)
    ? await prettier.resolveConfig(prettierConfigPath, {
        config: prettierConfigPath,
      })
    : null;

  const formatted = new Map<string, string>();
  for (const [relPath, content] of rawFiles) {
    formatted.set(
      relPath,
      await prettier.format(content, {
        ...(prettierOptions ?? {}),
        parser: relPath.endsWith('.ts') ? 'typescript' : 'markdown',
      }),
    );
  }
  return formatted;
}

function findReferenceOrphans(root: string): string[] {
  const refDir = path.join(root, 'docs/reference');
  if (!existsSync(refDir)) return [];
  const expectedSet = new Set<string>([
    ...GENERATED_REFERENCE_DOCS.map((rel) => path.basename(rel)),
    ...ALLOWED_NON_DOC_REFERENCE_FILES,
  ]);
  return readdirSync(refDir)
    .filter((name) => !expectedSet.has(name))
    .map((name) => `docs/reference/${name}`)
    .sort(compareText);
}

export async function syncDocs(
  options: { readonly root?: string } = {},
): Promise<{ readonly changed: boolean; readonly written: readonly string[] }> {
  const root = options.root ?? REPO_ROOT;
  const expected = await buildGeneratedDocsMap(root);
  const written: string[] = [];

  for (const [relPath, content] of expected) {
    const absPath = path.join(root, relPath);
    mkdirSync(path.dirname(absPath), { recursive: true });
    const prev = existsSync(absPath) ? readFileSync(absPath, 'utf8') : null;
    if (prev !== content) {
      writeFileSync(absPath, content, 'utf8');
      written.push(relPath);
    }
  }

  for (const orphanRel of findReferenceOrphans(root)) {
    rmSync(path.join(root, orphanRel), { recursive: true, force: true });
    written.push(orphanRel);
  }

  return { changed: written.length > 0, written: written.sort(compareText) };
}

export async function run(options: { readonly root?: string } = {}): Promise<CheckResult> {
  const root = options.root ?? REPO_ROOT;
  let expected: Map<string, string>;
  try {
    expected = await buildGeneratedDocsMap(root);
  } catch (err) {
    return fail('generated-docs failed to build', [
      err instanceof Error ? err.message : String(err),
    ]);
  }

  const problems: string[] = [];
  for (const [relPath, content] of expected) {
    const absPath = path.join(root, relPath);
    const current = existsSync(absPath) ? readFileSync(absPath, 'utf8') : null;
    if (current !== content) {
      problems.push(relPath);
    }
  }

  for (const orphanRel of findReferenceOrphans(root)) {
    problems.push(`orphan file in docs/reference/: ${orphanRel}`);
  }

  if (problems.length > 0) {
    return fail(
      `${String(problems.length)} reference doc issue(s) — run \`${SYNC_DOCS_COMMAND}\``,
      problems,
    );
  }

  return pass(`${String(expected.size)} generated reference doc target(s) up to date`);
}
