// main/tools/catalog/command.test.ts
/**
 * `bslt db catalog` without a database: the attribution result is given, the
 * command decides what to write and what to refuse. The computation itself runs
 * on a real database in `tests/integration/database/db-catalog.real-db.test.ts`.
 */
import { existsSync, mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';

import { afterEach, describe, expect, it } from 'vitest';

import { catalogCommand, run } from './command';
import { DB_CATALOG, loadCatalog, serializeCatalog } from './file';
import { attributedTo, soundCatalog, table } from './fixtures';

import type { AttributionResult } from './attribute';

const roots: string[] = [];

afterEach(() => {
  for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true });
});

function emptyRoot(): string {
  const root = mkdtempSync(path.join(tmpdir(), 'bslt-db-catalog-'));
  roots.push(root);
  return root;
}

function harness(result: AttributionResult): {
  root: string;
  lines: string[];
  catalog: (argv: readonly string[]) => Promise<number>;
} {
  const root = emptyRoot();
  const lines: string[] = [];
  const out = {
    log: (line: string) => lines.push(line),
    error: (line: string) => lines.push(line),
  };
  return {
    root,
    lines,
    catalog: (argv) =>
      catalogCommand(argv, {
        root,
        out,
        build: () => Promise.resolve(result),
        nullableOwnerColumns: {},
      }),
  };
}

const SOUND: AttributionResult = { catalog: soundCatalog(), problems: [] };

describe('bslt db catalog', () => {
  it('writes the catalog, with the header of its command, and reads it back', async () => {
    const { root, lines, catalog } = harness(SOUND);

    expect(await catalog([])).toBe(0);

    const written = readFileSync(path.join(root, DB_CATALOG.file), 'utf8');
    expect(written).toBe(serializeCatalog(soundCatalog()));
    expect(Object.keys(JSON.parse(written) as object)[0]).toBe('generated');
    expect(written).toContain('@generated by `pnpm bslt db catalog`');
    expect(loadCatalog(root)).toEqual(soundCatalog());
    expect(lines.join('\n')).toContain(`wrote ${DB_CATALOG.file}`);

    expect(await catalog([])).toBe(0);
    expect(lines.at(-1)).toBe(`${DB_CATALOG.file} is up to date.`);
  });

  it('--check compares and leaves the file alone', async () => {
    const { root, catalog } = harness(SOUND);
    expect(await catalog(['--check'])).toBe(1);
    expect(existsSync(path.join(root, DB_CATALOG.file))).toBe(false);

    await catalog([]);
    expect(await catalog(['--check'])).toBe(0);

    const changed = soundCatalog();
    const drifted = harness({
      catalog: { ...changed, tables: changed.tables.filter((entry) => entry.name !== 'tasks') },
      problems: [],
    });
    await catalogCommand([], {
      root: drifted.root,
      out: { log: () => undefined, error: () => undefined },
      build: () => Promise.resolve(SOUND),
      nullableOwnerColumns: {},
    });
    expect(await drifted.catalog(['--check'])).toBe(1);
    expect(drifted.lines.join('\n')).toContain('pnpm bslt db catalog');
  });

  it("writes nothing when a source alters another source's object", async () => {
    const { root, lines, catalog } = harness({
      catalog: soundCatalog(),
      problems: ['tasks alters table public.users, which identity created (columns)'],
    });

    expect(await catalog([])).toBe(1);

    expect(existsSync(path.join(root, DB_CATALOG.file))).toBe(false);
    expect(lines.join('\n')).toContain('tasks alters table public.users');
    expect(lines.join('\n')).toContain('was not written');
  });

  it('writes nothing when a table is unclassified or not its class', async () => {
    const sound = soundCatalog();
    const { root, lines, catalog } = harness({
      catalog: {
        ...sound,
        tables: [...sound.tables, attributedTo('tasks', table('notes', { comment: null }))],
      },
      problems: [],
    });

    expect(await catalog([])).toBe(1);

    expect(existsSync(path.join(root, DB_CATALOG.file))).toBe(false);
    expect(lines.join('\n')).toContain('table public.notes: no row-level security class');
  });

  it('refuses an argument it does not know', async () => {
    const { lines, catalog } = harness(SOUND);

    expect(await catalog(['--frobnicate'])).toBe(1);
    expect(lines.join('\n')).toContain('Usage: bslt db catalog [--check]');
  });

  it('loadCatalog names the command when the file is missing', () => {
    expect(() => loadCatalog(emptyRoot())).toThrow(/pnpm bslt db catalog/u);
  });
});

describe('the db-catalog gate', () => {
  it('in the self-test checks the form of the committed file, without a database', async () => {
    const { root, catalog } = harness(SOUND);
    expect((await run({ selfTest: true, root })).ok).toBe(false);

    await catalog([]);
    const result = await run({ selfTest: true, root });
    expect(result.ok).toBe(true);
    expect(result.summary).toContain('content not compared');
  });

  it('otherwise recomputes the catalog and compares', async () => {
    const { root, catalog } = harness(SOUND);
    await catalog([]);

    expect(
      await run({
        selfTest: false,
        root,
        build: () => Promise.resolve(SOUND),
        nullableOwnerColumns: {},
      }),
    ).toMatchObject({ ok: true });
    const sound = soundCatalog();
    const drifted = await run({
      selfTest: false,
      root,
      build: () => Promise.resolve({ catalog: { ...sound, extensions: ['other'] }, problems: [] }),
      nullableOwnerColumns: {},
    });
    expect(drifted.ok).toBe(false);
    expect((drifted.problems ?? []).join('\n')).toContain('pnpm bslt db catalog');
  });

  it('is the committed catalog of this repository', async () => {
    expect(await run({ selfTest: true })).toMatchObject({ ok: true });
  });
});
