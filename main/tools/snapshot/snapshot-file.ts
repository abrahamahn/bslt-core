// main/tools/snapshot/snapshot-file.ts
/**
 * The committed oracle snapshots (restructure plan, sections 14.2 and 14.3).
 *
 * A snapshot is a committed JSON file that records a surface of the product as
 * it is: the API routes and the web routes under `main/tools/snapshots/`
 * (`bslt snapshot <id>`), and the database catalog next to the migrations it is
 * computed from (`bslt db catalog`, ../catalog/file.ts). A command derives it
 * from the code or from a scratch database, and a gate compares the committed
 * file with what the command derives now. An unintended difference fails; an intended one is
 * committed with the change that caused it.
 *
 * The rules every snapshot follows:
 * - committed, sorted and deterministic: two runs on the same tree are
 *   byte-identical;
 * - the first key, `generated`, names the command that wrote the file;
 * - nobody edits the file by hand.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { fail, pass, type CheckResult } from '../gates/types';
import { REPO_ROOT } from '../lib/paths';

export interface SnapshotSpec {
  /** The argument of `bslt snapshot <id>`. */
  readonly id: string;
  /** Path of the committed file, relative to the repository root. */
  readonly file: string;
  /** What the snapshot records, for messages ("API surface"). */
  readonly title: string;
  /** What the snapshot is derived from, for the header. */
  readonly sources: string;
  /** The command that rewrites the file. Default: `pnpm bslt snapshot <id>`. */
  readonly command?: string;
}

/**
 * Order two strings by code unit. Snapshots never sort with `localeCompare`:
 * its order depends on the ICU data of the machine.
 */
export function compareText(left: string, right: string): number {
  return left < right ? -1 : left > right ? 1 : 0;
}

