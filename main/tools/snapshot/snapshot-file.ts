/** The command that rewrites a snapshot. */
export function snapshotCommand(spec: SnapshotSpec): string {
  return spec.command ?? `pnpm bslt snapshot ${spec.id}`;
}

/** The value of the `generated` key. */
export function snapshotHeader(spec: SnapshotSpec): string {
  return `@generated by \`${snapshotCommand(spec)}\` from ${spec.sources}. Do not edit: run the command and commit the result.`;
}

/**
 * The file content of a snapshot: the header, then `body`, as two-space JSON
 * with a final newline. Key order is the caller's: a snapshot module builds its
 * objects in a fixed order and sorts its lists.
 */
export function serializeSnapshot(
  spec: SnapshotSpec,
  body: Readonly<Record<string, unknown>>,
): string {
  if ('generated' in body) {
    throw new Error(`snapshot ${spec.id}: "generated" is the header key, the body must not set it`);
  }
  return `${JSON.stringify({ generated: snapshotHeader(spec), ...body }, null, 2)}\n`;
}

const DIFF_LIMIT = 60;
/** Above this many differing lines on either side, the middle is not aligned. */
const ALIGN_LIMIT = 8000;

/** Longest-common-subsequence alignment of two line lists, as edit operations. */
function alignLines(
  removed: readonly string[],
  added: readonly string[],
): Array<{ kind: 'same' | 'removed' | 'added'; line: string }> {
  const rows = removed.length;
  const columns = added.length;
  const width = columns + 1;
  // lengths[i * width + j]: the common subsequence length of removed[i..] and added[j..].
  const lengths = new Uint32Array((rows + 1) * width);
  for (let i = rows - 1; i >= 0; i -= 1) {
    for (let j = columns - 1; j >= 0; j -= 1) {
      lengths[i * width + j] =
        removed[i] === added[j]
          ? (lengths[(i + 1) * width + j + 1] ?? 0) + 1
          : Math.max(lengths[(i + 1) * width + j] ?? 0, lengths[i * width + j + 1] ?? 0);
    }
  }
  const operations: Array<{ kind: 'same' | 'removed' | 'added'; line: string }> = [];
  let i = 0;
  let j = 0;
  while (i < rows && j < columns) {
    const left = removed[i] ?? '';
    const right = added[j] ?? '';
    if (left === right) {
      operations.push({ kind: 'same', line: left });
      i += 1;
      j += 1;
    } else if ((lengths[(i + 1) * width + j] ?? 0) >= (lengths[i * width + j + 1] ?? 0)) {
      operations.push({ kind: 'removed', line: left });
      i += 1;
    } else {
      operations.push({ kind: 'added', line: right });
      j += 1;
    }
  }
  for (; i < rows; i += 1) operations.push({ kind: 'removed', line: removed[i] ?? '' });
  for (; j < columns; j += 1) operations.push({ kind: 'added', line: added[j] ?? '' });
  return operations;
}

/**
 * The changed lines between the committed text and the current text: a
 * `@@ line N @@` marker (a line number of the committed text) before each run of
 * `- removed` and `+ added` lines. At most `limit` lines, then a count of the
 * rest. Empty when the texts are equal.
 */
export function diffLines(committed: string, current: string, limit = DIFF_LIMIT): string[] {
  if (committed === current) return [];
  const before = committed.split('\n');
  const after = current.split('\n');
  let start = 0;
  while (start < before.length && start < after.length && before[start] === after[start]) {
    start += 1;
  }
  let endBefore = before.length;
  let endAfter = after.length;
  while (endBefore > start && endAfter > start && before[endBefore - 1] === after[endAfter - 1]) {
    endBefore -= 1;
    endAfter -= 1;
  }
  const removed = before.slice(start, endBefore);
  const added = after.slice(start, endAfter);
  const operations =
    removed.length > ALIGN_LIMIT || added.length > ALIGN_LIMIT
      ? [
          ...removed.map((line) => ({ kind: 'removed' as const, line })),
          ...added.map((line) => ({ kind: 'added' as const, line })),
        ]
      : alignLines(removed, added);

  const lines: string[] = [];
  let lineNumber = start + 1;
  let inHunk = false;
  for (const operation of operations) {
    if (operation.kind === 'same') {
      inHunk = false;
      lineNumber += 1;
      continue;
    }
    if (!inHunk) {
      lines.push(`@@ line ${String(lineNumber)} @@`);
      inHunk = true;
    }
    lines.push(`${operation.kind === 'removed' ? '-' : '+'} ${operation.line}`);
    if (operation.kind === 'removed') lineNumber += 1;
  }
  if (lines.length <= limit) return lines;
  return [...lines.slice(0, limit), `... ${String(lines.length - limit)} more changed line(s)`];
}

function updateHint(spec: SnapshotSpec): string[] {
  return [
    `If the change is intended: run \`${snapshotCommand(spec)}\`, commit ${spec.file} with the change that caused it, and describe the difference in the pull request.`,
    'If it is not intended, the code changed a surface it should not have: fix the code, not the snapshot.',
  ];
}

/**
 * Compare the committed snapshot with `current` (what the command derives now).
 *
 * @param spec - The snapshot.
 * @param current - Its content as `serializeSnapshot` returns it.
 * @param root - Repository root.
 */
export function checkSnapshot(
  spec: SnapshotSpec,
  current: string,
  root: string = REPO_ROOT,
): CheckResult {
  const file = path.join(root, spec.file);
  if (!existsSync(file)) {
    return fail(`${spec.file} does not exist`, [
      `Run \`${snapshotCommand(spec)}\` and commit the file.`,
    ]);
  }
  const committed = readFileSync(file, 'utf8');
  if (committed === current) return pass(`${spec.title} matches ${spec.file}`);
  return fail(`${spec.title} differs from ${spec.file}`, [
    '- committed, + current:',
    ...diffLines(committed, current),
    ...updateHint(spec),
  ]);
}

/**
 * Check the committed file without deriving anything: it exists, carries the
 * header of its command and is in the form `serializeSnapshot` writes. This is
 * what can be said about a snapshot whose source (a database) is not at hand.
 */
export function checkSnapshotForm(spec: SnapshotSpec, root: string = REPO_ROOT): CheckResult {
  const file = path.join(root, spec.file);
  if (!existsSync(file)) {
    return fail(`${spec.file} does not exist`, [
      `Run \`${snapshotCommand(spec)}\` and commit the file.`,
    ]);
  }
  const committed = readFileSync(file, 'utf8');
  let parsed: unknown;
  try {
    parsed = JSON.parse(committed);
  } catch (error) {
    return fail(`${spec.file} is not JSON`, [
      error instanceof Error ? error.message : String(error),
    ]);
  }
  const problems: string[] = [];
  if (typeof parsed !== 'object' || parsed === null || Array.isArray(parsed)) {
    problems.push('the file is not a JSON object');
  } else {
    const [firstKey] = Object.keys(parsed);
    if (
      firstKey !== 'generated' ||
      (parsed as { generated?: unknown }).generated !== snapshotHeader(spec)
    ) {
      problems.push(`the first key is not the header of \`${snapshotCommand(spec)}\``);
    }
    if (`${JSON.stringify(parsed, null, 2)}\n` !== committed) {
      problems.push(
        'the file is not in the form the command writes (it was edited or reformatted)',
      );
    }
  }
  if (problems.length > 0) {
    return fail(`${spec.file} is not a snapshot its command wrote`, [
      ...problems,
      `Run \`${snapshotCommand(spec)}\` and commit the result.`,
    ]);
  }
  return pass(
    `${spec.file} is in the form \`${snapshotCommand(spec)}\` writes (content not compared)`,
  );
}

/**
 * Write the snapshot file.
 *
 * @returns Whether the file changed.
 */
export function writeSnapshot(
  spec: SnapshotSpec,
  current: string,
  root: string = REPO_ROOT,
): boolean {
  const file = path.join(root, spec.file);
  if (existsSync(file) && readFileSync(file, 'utf8') === current) return false;
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, current);
  return true;
}
