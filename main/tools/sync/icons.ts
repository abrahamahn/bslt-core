// main/tools/sync/icons.ts
/**
 * `bslt sync icons`: generates `main/kernel/ui/src/icons.generated.ts` (`IconName`,
 * structured SVG node definitions, and `<symbol>` sprite map) from owned SVG
 * files in `main/kernel/ui/icons/*.svg` (plan sections 12.5 and 14.2).
 */

import fs from 'node:fs';
import path from 'node:path';

import { format, resolveConfig } from 'prettier';

import { fail, pass, type CheckResult } from '../gates/types';
import { REPO_ROOT } from '../lib/paths';

export const SYNC_ICONS_COMMAND = 'pnpm bslt sync icons';
export const GENERATED_ICONS_FILE = 'main/kernel/ui/src/icons.generated.ts';

const ICONS_REL_DIR = 'main/kernel/ui/icons';
const KEBAB_NAME_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/u;
const ALLOWED_TAGS = new Set(['path', 'circle', 'rect', 'line', 'polyline']);

interface ParsedIconNode {
  readonly tag: 'path' | 'circle' | 'rect' | 'line' | 'polyline';
  readonly attrs: Readonly<Record<string, string>>;
}

interface ParsedSvgIcon {
  readonly name: string;
  readonly viewBox: string;
  readonly fill: string;
  readonly stroke?: string | undefined;
  readonly strokeWidth?: string | undefined;
  readonly strokeLinecap?: string | undefined;
  readonly strokeLinejoin?: string | undefined;
  readonly nodes: readonly ParsedIconNode[];
  readonly symbolInnerSvg: string;
}

function parseAttributes(rawAttrs: string, context: string): Record<string, string> {
  const attrs: Record<string, string> = {};
  const attrRe = /([a-zA-Z_:][-a-zA-Z0-9_:.]*)\s*=\s*"([^"]*)"/gu;
  for (const match of rawAttrs.matchAll(attrRe)) {
    const rawKey = match[1];
    const value = match[2];
    if (rawKey === undefined || value === undefined) continue;
    if (rawKey.toLowerCase().startsWith('on')) {
      throw new Error(`${context}: event attribute "${rawKey}" is forbidden in SVG icons`);
    }
    const camelKey = rawKey.replace(/-([a-z])/gu, (_m, ch: string) => ch.toUpperCase());
    attrs[camelKey] = value;
  }
  return attrs;
}

function parseSvgFile(name: string, filePath: string): ParsedSvgIcon {
  const raw = fs.readFileSync(filePath, 'utf8').trim();
  const rootMatch = /^<svg\b([^>]*)>([\s\S]*?)<\/svg>$/iu.exec(raw);
  if (rootMatch === null) {
    throw new Error(`${ICONS_REL_DIR}/${name}.svg: expected a single <svg>...</svg> root`);
  }

  const rootAttrs = parseAttributes(rootMatch[1] ?? '', `${ICONS_REL_DIR}/${name}.svg`);
  const inner = (rootMatch[2] ?? '').trim();

  const elementRe = /<\/?([a-zA-Z][a-zA-Z0-9]*)\b([^>]*?)\/?>/gu;
  const nodes: ParsedIconNode[] = [];

  for (const match of inner.matchAll(elementRe)) {
    const full = match[0];
    const tag = (match[1] ?? '').toLowerCase();
    const attrText = match[2] ?? '';
    if (full.startsWith('</')) continue;
    if (!ALLOWED_TAGS.has(tag)) {
      throw new Error(
        `${ICONS_REL_DIR}/${name}.svg: unsupported SVG element <${tag}> (allowed: path, circle, rect, line, polyline)`,
      );
    }
    const attrs = parseAttributes(attrText, `${ICONS_REL_DIR}/${name}.svg`);
    nodes.push({
      tag: tag as ParsedIconNode['tag'],
      attrs,
    });
  }

  if (nodes.length === 0) {
    throw new Error(`${ICONS_REL_DIR}/${name}.svg: icon contains zero vector shape elements`);
  }

  return {
    name,
    viewBox: rootAttrs['viewBox'] ?? '0 0 24 24',
    fill: rootAttrs['fill'] ?? 'none',
    ...(rootAttrs['stroke'] !== undefined ? { stroke: rootAttrs['stroke'] } : {}),
    ...(rootAttrs['strokeWidth'] !== undefined ? { strokeWidth: rootAttrs['strokeWidth'] } : {}),
    ...(rootAttrs['strokeLinecap'] !== undefined
      ? { strokeLinecap: rootAttrs['strokeLinecap'] }
      : {}),
    ...(rootAttrs['strokeLinejoin'] !== undefined
      ? { strokeLinejoin: rootAttrs['strokeLinejoin'] }
      : {}),
    nodes,
    symbolInnerSvg: inner.replace(/\s+/gu, ' ').trim(),
  };
}

export async function renderIconsGeneratedTs(root: string = REPO_ROOT): Promise<string> {
  const iconsDir = path.join(root, ICONS_REL_DIR);
  if (!fs.existsSync(iconsDir)) {
    throw new Error(`Missing icons directory: ${ICONS_REL_DIR}`);
  }

  const entries = fs
    .readdirSync(iconsDir)
    .filter((file) => file.endsWith('.svg'))
    .sort((a, b) => a.localeCompare(b));

  if (entries.length === 0) {
    throw new Error(`${ICONS_REL_DIR}: found no .svg icon files`);
  }

  const parsed: ParsedSvgIcon[] = [];
  for (const entry of entries) {
    const name = entry.slice(0, -'.svg'.length);
    if (!KEBAB_NAME_RE.test(name)) {
      throw new Error(
        `${ICONS_REL_DIR}/${entry}: icon file name "${name}" must be lowercase kebab-case`,
      );
    }
    parsed.push(parseSvgFile(name, path.join(iconsDir, entry)));
  }

  const lines: string[] = [
    '// main/kernel/ui/src/icons.generated.ts',
    '// @generated by bslt sync icons from main/kernel/ui/icons/*.svg. Do not edit.',
    '',
    'export interface IconNode {',
    "  readonly tag: 'path' | 'circle' | 'rect' | 'line' | 'polyline';",
    '  readonly attrs: Readonly<Record<string, string>>;',
    '}',
    '',
    'export interface IconDefinition {',
    '  readonly viewBox: string;',
    '  readonly fill: string;',
    '  readonly stroke?: string | undefined;',
    '  readonly strokeWidth?: string | undefined;',
    '  readonly strokeLinecap?: string | undefined;',
    '  readonly strokeLinejoin?: string | undefined;',
    '  readonly nodes: readonly IconNode[];',
    '}',
    '',
    'export type IconName =',
    ...parsed.map(
      (icon, index) =>
        `  | '${icon.name}'${index === parsed.length - 1 ? ';' : ''} // <- ${ICONS_REL_DIR}/${icon.name}.svg`,
    ),
    '',
    'export const ICONS: Readonly<Record<IconName, IconDefinition>> = {',
  ];

  for (const icon of parsed) {
    lines.push(`  // <- ${ICONS_REL_DIR}/${icon.name}.svg`);
    lines.push(
      `  '${icon.name}': ${JSON.stringify(
        {
          viewBox: icon.viewBox,
          fill: icon.fill,
          ...(icon.stroke !== undefined ? { stroke: icon.stroke } : {}),
          ...(icon.strokeWidth !== undefined ? { strokeWidth: icon.strokeWidth } : {}),
          ...(icon.strokeLinecap !== undefined ? { strokeLinecap: icon.strokeLinecap } : {}),
          ...(icon.strokeLinejoin !== undefined ? { strokeLinejoin: icon.strokeLinejoin } : {}),
          nodes: icon.nodes,
        },
        null,
        2,
      )},`,
    );
  }

  lines.push('};');
  lines.push('');
  lines.push('export const ICON_SPRITE = [');
  lines.push(`  '<svg xmlns="http://www.w3.org/2000/svg" hidden aria-hidden="true">',`);
  for (const icon of parsed) {
    lines.push(
      `  ${JSON.stringify(`<symbol id="bslt-icon-${icon.name}" viewBox="${icon.viewBox}">${icon.symbolInnerSvg}</symbol>`)}, // <- ${ICONS_REL_DIR}/${icon.name}.svg`,
    );
  }
  lines.push(`  '</svg>',`);
  lines.push("].join('');");
  lines.push('');

  const prettierConfig =
    (await resolveConfig(path.join(REPO_ROOT, 'config/.prettierrc'), {
      config: path.join(REPO_ROOT, 'config/.prettierrc'),
    })) ?? {};

  return format(lines.join('\n'), {
    ...prettierConfig,
    parser: 'typescript',
  });
}

export async function syncIcons(
  options: { readonly root?: string } = {},
): Promise<{ readonly changed: boolean; readonly count: number }> {
  const root = options.root ?? REPO_ROOT;
  const targetPath = path.join(root, GENERATED_ICONS_FILE);
  const expected = await renderIconsGeneratedTs(root);
  const existing = fs.existsSync(targetPath) ? fs.readFileSync(targetPath, 'utf8') : null;
  const changed = existing !== expected;
  if (changed) {
    fs.mkdirSync(path.dirname(targetPath), { recursive: true });
    fs.writeFileSync(targetPath, expected, 'utf8');
  }
  const count = fs
    .readdirSync(path.join(root, ICONS_REL_DIR))
    .filter((f) => f.endsWith('.svg')).length;
  return { changed, count };
}

export async function run(options: { readonly root?: string } = {}): Promise<CheckResult> {
  const root = options.root ?? REPO_ROOT;
  const targetPath = path.join(root, GENERATED_ICONS_FILE);
  let expected: string;
  try {
    expected = await renderIconsGeneratedTs(root);
  } catch (error) {
    return fail(error instanceof Error ? error.message : String(error));
  }
  if (!fs.existsSync(targetPath)) {
    return fail(`${GENERATED_ICONS_FILE} is missing; run \`${SYNC_ICONS_COMMAND}\``);
  }
  const actual = fs.readFileSync(targetPath, 'utf8');
  if (actual !== expected) {
    return fail(`${GENERATED_ICONS_FILE} is out of date; run \`${SYNC_ICONS_COMMAND}\``);
  }
  const count = fs
    .readdirSync(path.join(root, ICONS_REL_DIR))
    .filter((f) => f.endsWith('.svg')).length;
  return pass(`${GENERATED_ICONS_FILE} matches ${String(count)} owned SVG icons`);
}
