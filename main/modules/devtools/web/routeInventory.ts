function coverageRouteKey(route: ApiRouteDefinition): string {
  return `${route.method} ${route.path}`;
}

function canRunGeneratedGetSmoke(route: ApiRouteDefinition): boolean {
  if (route.method !== 'GET') return false;
  if (route.path.includes(':')) return false;
  if (route.path.includes('/callback')) return false;
  if (OAUTH_INITIATE_PATH_PATTERN.test(route.path)) return false;
  if (!route.public && QUERY_FIXTURE_REQUIRED_PATHS.has(route.path)) return false;
  if (!route.public && HEADER_FIXTURE_REQUIRED_PATHS.has(route.path)) return false;
  return true;
}

export function getApiRouteCoverage(route: ApiRouteDefinition): ApiRouteCoverage {
  const key = coverageRouteKey(route);
  let smoke: CoverageStatus = 'Pending';

  if (MUTATION_SMOKE_ROUTE_KEYS.has(key)) {
    smoke = 'Mutation smoke';
  } else if (FIXTURE_GET_ROUTE_KEYS.has(key)) {
    smoke = 'Fixture GET';
  } else if (canRunGeneratedGetSmoke(route)) {
    smoke = 'GET smoke';
  }

  return {
    frontend: EXTERNAL_CALLBACK_ROUTE_KEYS.has(key)
      ? 'External callback'
      : FRONTEND_CALLER_ROUTE_KEYS.has(key)
        ? 'Product workflow'
        : 'No product workflow',
    note: COVERAGE_NOTES.get(key) ?? null,
    smoke,
  };
}
