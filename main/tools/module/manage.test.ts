// main/tools/module/manage.test.ts
import { existsSync, mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import http from 'node:http';
import { tmpdir } from 'node:os';
import path from 'node:path';

import { afterEach, describe, expect, it } from 'vitest';

import { createDeterministicTarGz, sha256Hex } from './archive';
import { addModules, listModules, removeModules } from './manage';
import { MODULES_CATALOG_FILENAME, releaseOptionalModules } from './release';

const tempDirs: string[] = [];
const openServers: http.Server[] = [];

function makeTempDir(prefix: string): string {
  const dir = mkdtempSync(path.join(tmpdir(), prefix));
  tempDirs.push(dir);
  return dir;
}

function createMinimalCoreWorkspace(): { readonly coreRoot: string; readonly catalogDir: string } {
  const sourceRoot = makeTempDir('bslt-manage-src-');
  const coreRoot = makeTempDir('bslt-manage-core-');
  const catalogDir = makeTempDir('bslt-manage-catalog-');

  for (const root of [sourceRoot, coreRoot]) {
    mkdirSync(path.join(root, 'config'), { recursive: true });
    writeFileSync(
      path.join(root, 'config/.prettierrc'),
      JSON.stringify({ singleQuote: true, trailingComma: 'all', printWidth: 100 }, null, 2),
    );
    mkdirSync(path.join(root, 'main/apps/server/src'), { recursive: true });
    mkdirSync(path.join(root, 'main/apps/web/src'), { recursive: true });
    mkdirSync(path.join(root, 'main/kernel/db/sql'), { recursive: true });
    mkdirSync(path.join(root, 'main/kernel/db/src/generated'), { recursive: true });
    mkdirSync(path.join(root, 'main/kernel/web/src/ssr'), { recursive: true });
    mkdirSync(path.join(root, 'main/modules/identity/server/migrations'), { recursive: true });
    mkdirSync(path.join(root, 'tests/integration/database/generated'), { recursive: true });
    const kernelSql = '-- 0001_sys.sql\nSELECT 1;\n';
    const identitySql = '-- 0001_identity.sql\nSELECT 1;\n';
    writeFileSync(path.join(root, 'main/kernel/db/sql/0001_sys.sql'), kernelSql);
    writeFileSync(
      path.join(root, 'main/modules/identity/server/migrations/0001_identity.sql'),
      identitySql,
    );
    writeFileSync(
      path.join(root, 'package.json'),
      JSON.stringify(
        {
          name: '@bslt/root',
          version: '1.0.0',
          private: true,
          scripts: {
            postbuild:
              'bslt-esm-fix main/kernel/schema/dist main/modules/identity/dist main/modules/compliance/dist main/modules/audit/dist main/modules/devtools/dist main/apps/server/dist && bslt gate run esm-dist',
          },
          devDependencies: {
            '@bslt/audit': 'workspace:*',
            '@bslt/compliance': 'workspace:*',
            '@bslt/contract': 'workspace:*',
            '@bslt/devtools': 'workspace:*',
            '@bslt/identity': 'workspace:*',
          },
        },
        null,
        2,
      ),
    );
    writeFileSync(
      path.join(root, 'tsconfig.json'),
      JSON.stringify({ files: [], references: [] }, null, 2),
    );
    writeFileSync(
      path.join(root, 'main/apps/server/package.json'),
      JSON.stringify({ name: '@bslt/server', version: '1.0.0', dependencies: {} }, null, 2),
    );
    writeFileSync(
      path.join(root, 'main/apps/server/tsconfig.json'),
      JSON.stringify({ compilerOptions: { composite: true }, references: [] }, null, 2),
    );
    writeFileSync(
      path.join(root, 'main/apps/web/package.json'),
      JSON.stringify({ name: '@bslt/web', version: '1.0.0', dependencies: {} }, null, 2),
    );
    writeFileSync(
      path.join(root, 'main/apps/web/tsconfig.json'),
      JSON.stringify({ compilerOptions: { composite: true }, references: [] }, null, 2),
    );
    writeFileSync(
      path.join(root, 'bslt.lock.json'),
      JSON.stringify(
        {
          orgPermissionBits: {},
          tombstoned: [],
          migrations: {
            'kernel/0001_sys.sql': sha256Hex(Buffer.from(kernelSql)),
            'identity/0001_identity.sql': sha256Hex(Buffer.from(identitySql)),
          },
        },
        null,
        2,
      ),
    );
    writeFileSync(
      path.join(root, 'main/kernel/db/catalog.snapshot.json'),
      `${JSON.stringify(
        {
          generated:
            '@generated by `pnpm bslt db catalog` from pg_catalog of a scratch database, read after each migration source of @bslt/db (main/kernel/db/sql and main/kernel/db/legacy-migrations) was applied as bslt_owner, after the cluster role bootstrap. Do not edit: run the command and commit the result.',
          sources: [
            { id: 'kernel', dependsOn: [] },
            { id: 'identity', dependsOn: [] },
            { id: 'compliance', dependsOn: ['identity'] },
            { id: 'audit', dependsOn: [] },
          ],
          roles: [],
          extensions: [],
          schemas: [],
          types: [],
          sequences: [],
          functions: [],
          tables: [],
          views: [],
        },
        null,
        2,
      )}\n`,
    );

    // Core modules: identity, compliance, audit, devtools
    for (const coreMod of [
      { id: 'identity', deps: [] as string[] },
      { id: 'compliance', deps: ['identity'] },
      { id: 'audit', deps: [] as string[] },
      { id: 'devtools', deps: [] as string[] },
    ]) {
      mkdirSync(path.join(root, `main/modules/${coreMod.id}/server`), { recursive: true });
      mkdirSync(path.join(root, `main/modules/${coreMod.id}/web`), { recursive: true });
      writeFileSync(
        path.join(root, `main/modules/${coreMod.id}/package.json`),
        JSON.stringify({ name: `@bslt/${coreMod.id}`, version: '1.0.0' }, null, 2),
      );
      const depImports = coreMod.deps
        .map((d) => `import { ${d}Module } from '@bslt/${d}/module';`)
        .join('\n');
      const depList = coreMod.deps.map((d) => `${d}Module`).join(', ');
      writeFileSync(
        path.join(root, `main/modules/${coreMod.id}/module.ts`),
        `// main/modules/${coreMod.id}/module.ts
import { defineModule } from '@bslt/contract';
${depImports}
export const ${coreMod.id}Module = defineModule({
  id: '${coreMod.id}',
  summary: '${coreMod.id} module.',
  status: 'stable',
  dependsOn: [${depList}],
  endpoints: {},
  events: {},
  jobs: {},
  tables: [],
});
`,
      );
      writeFileSync(
        path.join(root, `main/modules/${coreMod.id}/server/index.ts`),
        `// main/modules/${coreMod.id}/server/index.ts\nexport const ${coreMod.id}Server = {};\n`,
      );
      writeFileSync(
        path.join(root, `main/modules/${coreMod.id}/web/index.ts`),
        `// main/modules/${coreMod.id}/web/index.ts\nexport const ${coreMod.id}Web = {};\n`,
      );
      writeFileSync(
        path.join(root, `main/modules/${coreMod.id}/README.md`),
        `# ${coreMod.id}\n\n<!-- bslt:generated reference -->\n<!-- /bslt:generated -->\n`,
      );
    }

    writeFileSync(
      path.join(root, 'bslt.config.ts'),
      `// bslt.config.ts
import { auditModule } from '@bslt/audit/module';
import { complianceModule } from '@bslt/compliance/module';
import { defineConfig } from '@bslt/contract';
import { devtoolsModule } from '@bslt/devtools/module';
import { identityModule } from '@bslt/identity/module';

export default defineConfig({
  name: 'BSLT',
  installedModules: [identityModule, complianceModule, auditModule] as const,
  devOnly: [devtoolsModule],
  locales: ['en-US'],
  brand: {
    accent: 'oklch(0.62 0.19 264)',
    logo: '/brand/logo.svg',
  },
});
`,
    );
  }

  // Add optional chain orgs -> entitlements -> billing in sourceRoot
  for (const optMod of [
    { id: 'orgs', deps: ['identity'], perms: ['orgs.members.invite'] },
    { id: 'entitlements', deps: ['identity', 'orgs'], perms: [] as string[] },
    { id: 'billing', deps: ['identity', 'orgs', 'entitlements'], perms: [] as string[] },
  ]) {
    mkdirSync(path.join(sourceRoot, `main/modules/${optMod.id}/server/migrations`), {
      recursive: true,
    });
    mkdirSync(path.join(sourceRoot, `main/modules/${optMod.id}/web`), { recursive: true });
    writeFileSync(
      path.join(sourceRoot, `main/modules/${optMod.id}/package.json`),
      JSON.stringify({ name: `@bslt/${optMod.id}`, version: '1.0.0' }, null, 2),
    );
    const depImports = optMod.deps
      .map((d) => `import { ${d}Module } from '@bslt/${d}/module';`)
      .join('\n');
    const depList = optMod.deps.map((d) => `${d}Module`).join(', ');
    const permsField =
      optMod.perms.length > 0
        ? `\n  permissions: [${optMod.perms.map((p) => `'${p}'`).join(', ')}],`
        : '';
    writeFileSync(
      path.join(sourceRoot, `main/modules/${optMod.id}/module.ts`),
      `// main/modules/${optMod.id}/module.ts
import { defineModule } from '@bslt/contract';
${depImports}
export const ${optMod.id}Module = defineModule({
  id: '${optMod.id}',
  summary: '${optMod.id} optional module.',
  status: 'stable',
  dependsOn: [${depList}],${permsField}
  endpoints: {},
  events: {},
  jobs: {},
  tables: [],
});
`,
    );
    const sql = `-- 0001_${optMod.id}.sql\nSELECT 1;\n`;
    writeFileSync(
      path.join(sourceRoot, `main/modules/${optMod.id}/server/migrations/0001_${optMod.id}.sql`),
      sql,
    );
    writeFileSync(
      path.join(sourceRoot, `main/modules/${optMod.id}/server/index.ts`),
      `// main/modules/${optMod.id}/server/index.ts\nexport const ${optMod.id}Server = {};\n${optMod.id === 'orgs' ? 'export const resolveActingOrg = async () => null;\n' : ''}`,
    );
    writeFileSync(
      path.join(sourceRoot, `main/modules/${optMod.id}/web/index.ts`),
      `// main/modules/${optMod.id}/web/index.ts\nexport const ${optMod.id}Web = {};\n`,
    );
    writeFileSync(
      path.join(sourceRoot, `main/modules/${optMod.id}/README.md`),
      `# ${optMod.id}\n\n<!-- bslt:generated reference -->\n<!-- /bslt:generated -->\n`,
    );
  }

  writeFileSync(
    path.join(sourceRoot, 'bslt.lock.json'),
    JSON.stringify(
      {
        orgPermissionBits: { 'orgs.members.invite': 0 },
        tombstoned: [],
        migrations: {
          'kernel/0001_sys.sql': sha256Hex(Buffer.from('-- 0001_sys.sql\nSELECT 1;\n')),
          'identity/0001_identity.sql': sha256Hex(Buffer.from('-- 0001_identity.sql\nSELECT 1;\n')),
          'orgs/0001_orgs.sql': sha256Hex(Buffer.from('-- 0001_orgs.sql\nSELECT 1;\n')),
          'entitlements/0001_entitlements.sql': sha256Hex(
            Buffer.from('-- 0001_entitlements.sql\nSELECT 1;\n'),
          ),
          'billing/0001_billing.sql': sha256Hex(Buffer.from('-- 0001_billing.sql\nSELECT 1;\n')),
        },
      },
      null,
      2,
    ),
  );
  writeFileSync(
    path.join(sourceRoot, 'main/kernel/db/catalog.snapshot.json'),
    `${JSON.stringify(
      {
        generated:
          '@generated by `pnpm bslt db catalog` from pg_catalog of a scratch database, read after each migration source of @bslt/db (main/kernel/db/sql and main/kernel/db/legacy-migrations) was applied as bslt_owner, after the cluster role bootstrap. Do not edit: run the command and commit the result.',
        sources: [
          { id: 'kernel', dependsOn: [] },
          { id: 'identity', dependsOn: [] },
          { id: 'orgs', dependsOn: ['identity'] },
          { id: 'entitlements', dependsOn: ['identity', 'orgs'] },
          { id: 'billing', dependsOn: ['identity', 'orgs', 'entitlements'] },
          { id: 'compliance', dependsOn: ['identity'] },
          { id: 'audit', dependsOn: [] },
        ],
        roles: [],
        extensions: [],
        schemas: [],
        types: [],
        sequences: [],
        functions: [],
        tables: [],
        views: [],
      },
      null,
      2,
    )}\n`,
  );

  // Store sourceRoot inside catalogDir marker for helper usage in tests
  writeFileSync(path.join(catalogDir, '.source-root'), sourceRoot);
  return { coreRoot, catalogDir };
}

afterEach(async () => {
  while (openServers.length > 0) {
    const srv = openServers.pop();
    if (srv !== undefined) {
      await new Promise<void>((resolve) => {
        srv.close(() => resolve());
      });
    }
  }
  while (tempDirs.length > 0) {
    const dir = tempDirs.pop();
    if (dir !== undefined) {
      rmSync(dir, { recursive: true, force: true });
    }
  }
});

describe('bslt module list | add | remove', () => {
  it('refuses removing Minimal Core modules', async () => {
    const { coreRoot } = createMinimalCoreWorkspace();
    await expect(
      removeModules({ root: coreRoot, ids: ['identity'], install: false }),
    ).rejects.toThrow(/core module/iu);
    await expect(
      removeModules({ root: coreRoot, ids: ['devtools'], install: false }),
    ).rejects.toThrow(/core module/iu);
  });

  it('resolves transitive dependsOn in topological order on add and blocks removing depended-on modules without --cascade', async () => {
    const { coreRoot, catalogDir } = createMinimalCoreWorkspace();
    const sourceRoot = readFileSync(path.join(catalogDir, '.source-root'), 'utf8');
    await releaseOptionalModules({ root: sourceRoot, outDir: catalogDir });

    // Dry-run does not write main/modules/billing
    const dryPlan = await addModules({
      root: coreRoot,
      targets: ['billing'],
      catalog: catalogDir,
      dryRun: true,
      install: false,
    });
    expect(dryPlan.addedIds).toEqual(['orgs', 'entitlements', 'billing']);
    expect(existsSync(path.join(coreRoot, 'main/modules/billing'))).toBe(false);

    // Real apply installs orgs -> entitlements -> billing
    const applied = await addModules({
      root: coreRoot,
      targets: ['billing'],
      catalog: catalogDir,
      install: false,
    });
    expect(applied.addedIds).toEqual(['orgs', 'entitlements', 'billing']);
    expect(existsSync(path.join(coreRoot, 'main/modules/orgs/module.ts'))).toBe(true);
    expect(existsSync(path.join(coreRoot, 'main/modules/entitlements/module.ts'))).toBe(true);
    expect(existsSync(path.join(coreRoot, 'main/modules/billing/module.ts'))).toBe(true);

    const configText = readFileSync(path.join(coreRoot, 'bslt.config.ts'), 'utf8');
    const installedBlock = /installedModules:\s*\[[\s\S]*?\]/u.exec(configText)?.[0] ?? '';
    expect(installedBlock.indexOf('orgsModule')).toBeLessThan(
      installedBlock.indexOf('entitlementsModule'),
    );
    expect(installedBlock.indexOf('entitlementsModule')).toBeLessThan(
      installedBlock.indexOf('billingModule'),
    );

    const lockText = JSON.parse(readFileSync(path.join(coreRoot, 'bslt.lock.json'), 'utf8')) as {
      orgPermissionBits: Record<string, number>;
      migrations: Record<string, string>;
    };
    expect(lockText.orgPermissionBits['orgs.members.invite']).toBe(0);
    expect(lockText.migrations['billing/0001_billing.sql']).toBeDefined();

    // Removing orgs while entitlements & billing depend on it must fail
    await expect(removeModules({ root: coreRoot, ids: ['orgs'], install: false })).rejects.toThrow(
      /entitlements|billing/iu,
    );

    // Listing modules shows installed + available
    const listing = await listModules({ root: coreRoot, catalog: catalogDir });
    expect(listing.installed.map((m) => m.id)).toContain('billing');

    // Cascade remove orgs removes billing, entitlements, and orgs cleanly
    const removed = await removeModules({
      root: coreRoot,
      ids: ['orgs'],
      cascade: true,
      install: false,
    });
    expect(removed.removedIds).toEqual(['billing', 'entitlements', 'orgs']);
    expect(existsSync(path.join(coreRoot, 'main/modules/billing'))).toBe(false);
    expect(existsSync(path.join(coreRoot, 'main/modules/orgs'))).toBe(false);
  });

  it('rejects tampered archive SHA-256 checksums and incompatible coreVersion catalogs', async () => {
    const { coreRoot, catalogDir } = createMinimalCoreWorkspace();
    const sourceRoot = readFileSync(path.join(catalogDir, '.source-root'), 'utf8');
    await releaseOptionalModules({ root: sourceRoot, outDir: catalogDir });

    // Tamper with orgs-1.0.0.tar.gz bytes
    const archivePath = path.join(catalogDir, 'orgs-1.0.0.tar.gz');
    writeFileSync(
      archivePath,
      createDeterministicTarGz([{ path: 'module.ts', content: Buffer.from('tampered') }]),
    );
    await expect(
      addModules({ root: coreRoot, targets: ['orgs'], catalog: catalogDir, install: false }),
    ).rejects.toThrow(/checksum mismatch/iu);

    // Incompatible coreVersion
    await releaseOptionalModules({ root: sourceRoot, outDir: catalogDir });
    const catalogPath = path.join(catalogDir, MODULES_CATALOG_FILENAME);
    const catalogJson = JSON.parse(readFileSync(catalogPath, 'utf8')) as Record<string, unknown>;
    catalogJson['coreVersion'] = '9.9.9';
    writeFileSync(catalogPath, JSON.stringify(catalogJson, null, 2));

    await expect(
      addModules({ root: coreRoot, targets: ['orgs'], catalog: catalogDir, install: false }),
    ).rejects.toThrow(/coreVersion|compatible/iu);
  });

  it('rejects insecure non-loopback HTTP URLs and never leaks BSLT_MODULE_TOKEN across redirect origins', async () => {
    const { coreRoot, catalogDir } = createMinimalCoreWorkspace();
    const sourceRoot = readFileSync(path.join(catalogDir, '.source-root'), 'utf8');
    await releaseOptionalModules({ root: sourceRoot, outDir: catalogDir });

    await expect(
      addModules({
        root: coreRoot,
        targets: ['orgs'],
        catalog: 'http://evil.example.com/modules.catalog.json',
        install: false,
      }),
    ).rejects.toThrow(/https/iu);

    let leakedAuthOnCrossOrigin: string | undefined;
    const archiveBytes = readFileSync(path.join(catalogDir, 'orgs-1.0.0.tar.gz'));
    const serverB = http.createServer((req, res) => {
      leakedAuthOnCrossOrigin = req.headers.authorization;
      res.writeHead(200, { 'content-type': 'application/gzip' });
      res.end(archiveBytes);
    });
    openServers.push(serverB);
    await new Promise<void>((resolve) => serverB.listen(0, '127.0.0.1', () => resolve()));
    const portB = (serverB.address() as { port: number }).port;

    let catalogAuthHeader: string | undefined;
    const serverA = http.createServer((req, res) => {
      if (req.url === '/modules.catalog.json') {
        catalogAuthHeader = req.headers.authorization;
        res.writeHead(200, { 'content-type': 'application/json' });
        res.end(readFileSync(path.join(catalogDir, MODULES_CATALOG_FILENAME)));
        return;
      }
      res.writeHead(302, { location: `http://127.0.0.1:${String(portB)}${req.url ?? ''}` });
      res.end();
    });
    openServers.push(serverA);
    await new Promise<void>((resolve) => serverA.listen(0, '127.0.0.1', () => resolve()));
    const portA = (serverA.address() as { port: number }).port;

    await addModules({
      root: coreRoot,
      targets: ['orgs'],
      catalog: `http://127.0.0.1:${String(portA)}/modules.catalog.json`,
      token: 'secret-bearer-token-123',
      install: false,
    });

    expect(catalogAuthHeader).toBe('Bearer secret-bearer-token-123');
    expect(leakedAuthOnCrossOrigin).toBeUndefined();
    expect(readFileSync(path.join(coreRoot, 'bslt.config.ts'), 'utf8')).not.toContain(
      'secret-bearer-token-123',
    );
  });
});
