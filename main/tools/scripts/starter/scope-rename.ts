// main/tools/scripts/starter/scope-rename.ts
/**
 * Package-scope migration helper.
 *
 * `bslt rename` intentionally leaves the internal workspace scope (`@bslt/*`)
 * untouched because renaming it touches ~1300 files. This command closes that
 * gap: it rewrites the scope token everywhere it is used as a package prefix —
 * source imports, package.json `name`/dependency keys, tsconfig `paths`,
 * Vite/Vitest aliases, turbo/pnpm `--filter=` selectors, and ESLint boundary
 * rules — so a fork can adopt `@acme/*` and still build green with zero `@bslt`
 * left behind.
 *
 * It anchors strictly on the scope prefix (`@bslt` immediately followed by `/`
 * or an escaped `\/` inside a regex literal). That means incidental product copy
 * ("BSLT"), URLs (`github.com/abrahamahn/bslt`), cache filenames
 * (`eslintcache-bslt-api`), and localStorage keys (`bslt-device-id`) are never
 * touched. The transform is idempotent: a second run is a no-op.
 *
 * The pnpm lockfile is deliberately excluded — it must be regenerated with
 * `pnpm install` after applying, not text-patched.
 */

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { REPO_ROOT } from '../../lib/paths';

import { PACKAGE_SCOPE_PATTERN } from './rename';

export const DEFAULT_FROM_SCOPE = '@bslt';

/** Text file extensions that can carry a package-scope token. */
const TEXT_EXTENSIONS: ReadonlySet<string> = new Set([
  '.ts',
  '.tsx',
  '.js',
  '.jsx',
  '.mjs',
  '.cjs',
  '.json',
  '.md',
  '.yml',
  '.yaml',
]);

/** Directories never worth scanning (generated, vendored, or VCS internals). */
const IGNORED_DIRS: ReadonlySet<string> = new Set([
  'node_modules',
  'dist',
  'build',
  'coverage',
  '.git',
  '.turbo',
  '.cache',
  '.next',
]);

/**
 * Files skipped even when they contain the token. The pnpm lockfile encodes the
 * scope in resolved keys but must be regenerated by `pnpm install`, not patched.
 */
const IGNORED_FILES: ReadonlySet<string> = new Set(['pnpm-lock.yaml']);

export interface ScopeRenameOptions {
  readonly fromScope: string;
  readonly toScope: string;
  readonly apply: boolean;
}

export interface ScopeRenameCliOptions {
  readonly fromScope: string;
  readonly toScope?: string | undefined;
  readonly apply: boolean;
}

export interface ScopeRenameEdit {
  readonly path: string;
  readonly occurrences: number;
}

export interface ScopeRenamePlan {
  readonly fromScope: string;
  readonly toScope: string;
  readonly apply: boolean;
  readonly edits: readonly ScopeRenameEdit[];
  readonly postApply: readonly string[];
}

export interface ScopeRenameApplyResult {
  readonly filesPatched: readonly string[];
}

export function usage(): string {
  return [
    'Usage: pnpm bslt rename scope <@scope> [--from <@scope>] [--apply]',
    '',
    'Examples:',
    '  pnpm bslt rename scope @acme            # dry run: list every file + edit count',
    '  pnpm bslt rename scope @acme --apply    # rewrite the whole workspace scope',
    '',
    'Options:',
    '  --apply   Write the scope migration. Without it, prints a dry-run plan.',
    `  --from    Source scope to replace. Defaults to "${DEFAULT_FROM_SCOPE}".`,
    '  --help    Show this help text.',
    '',
    'After --apply, run "pnpm install" to regenerate the lockfile.',
  ].join('\n');
}

function normalizeScope(value: string, label: string): string {
  const scope = value.trim().toLowerCase();
  if (scope === '') {
    throw new Error(`Missing ${label}.`);
  }
  if (!PACKAGE_SCOPE_PATTERN.test(scope)) {
    throw new Error(`Invalid ${label} "${value}". Use a scope like "@acme".`);
  }
  return scope;
}

function normalizeOptions(options: ScopeRenameCliOptions): ScopeRenameOptions {
  const fromScope = normalizeScope(options.fromScope, 'source scope');
  const toScope = normalizeScope(options.toScope ?? '', 'target scope');
  if (fromScope === toScope) {
    throw new Error(`Target scope must differ from the source scope (${fromScope}).`);
  }
  return { fromScope, toScope, apply: options.apply };
}

function escapeRegex(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/gu, '\\$&');
}

/**
 * Match the scope token only where it is a package prefix: `@bslt` immediately
 * followed by `/` (imports, names, paths, filters) or `\` (an escaped slash in a
 * regex literal such as `/^@bslt\/shared$/`). A lookahead keeps the delimiter.
 */
function scopePattern(fromScope: string): RegExp {
  return new RegExp(`${escapeRegex(fromScope)}(?=[/\\\\])`, 'gu');
}

/** Pure token transform. Idempotent when `toScope !== fromScope`. */
export function renameScopeToken(contents: string, fromScope: string, toScope: string): string {
  return contents.replace(scopePattern(fromScope), toScope);
}

function countScopeTokens(contents: string, fromScope: string): number {
  return contents.match(scopePattern(fromScope))?.length ?? 0;
}

function isTextCandidate(fileName: string): boolean {
  if (IGNORED_FILES.has(fileName)) return false;
  if (fileName === 'Dockerfile' || fileName.startsWith('Dockerfile.')) return true;
  return TEXT_EXTENSIONS.has(path.extname(fileName).toLowerCase());
}

function collectFiles(root: string): string[] {
  const results: string[] = [];

  function visit(directory: string): void {
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      const absolute = path.join(directory, entry.name);
      if (entry.isDirectory()) {
        if (!IGNORED_DIRS.has(entry.name)) visit(absolute);
      } else if (entry.isFile() && isTextCandidate(entry.name)) {
        results.push(absolute);
      }
    }
  }

  visit(root);
  return results.sort();
}

export function planScopeRename(
  options: ScopeRenameCliOptions & { readonly root: string },
): ScopeRenamePlan {
  const normalized = normalizeOptions(options);
  const { fromScope, toScope } = normalized;

  const edits: ScopeRenameEdit[] = [];
  for (const absolute of collectFiles(options.root)) {
    const occurrences = countScopeTokens(readFileSync(absolute, 'utf8'), fromScope);
    if (occurrences > 0) {
      edits.push({
        path: path.relative(options.root, absolute).split(path.sep).join('/'),
        occurrences,
      });
    }
  }

  return {
    fromScope,
    toScope,
    apply: normalized.apply,
    edits,
    postApply: [
      `Run "pnpm install" to regenerate pnpm-lock.yaml and workspace links for the ${toScope} scope.`,
      'The tsconfig "references" arrays are path-based (not scope-based) and need no change; "pnpm sync:ts" stays green.',
    ],
  };
}

export function applyScopeRenamePlan(plan: ScopeRenamePlan, root: string): ScopeRenameApplyResult {
  const filesPatched: string[] = [];
  for (const edit of plan.edits) {
    const absolute = path.join(root, edit.path);
    const contents = readFileSync(absolute, 'utf8');
    const next = renameScopeToken(contents, plan.fromScope, plan.toScope);
    if (next !== contents) {
      writeFileSync(absolute, next, 'utf8');
      filesPatched.push(edit.path);
    }
  }
  return { filesPatched };
}

export function parseScopeRenameArgs(args: readonly string[]): ScopeRenameCliOptions {
  let toScope: string | undefined;
  let fromScope = DEFAULT_FROM_SCOPE;
  let apply = false;

  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];
    if (arg === undefined) continue;
    if (arg === '--help' || arg === '-h') {
      console.log(usage());
      process.exit(0);
    }
    if (arg === '--apply') {
      apply = true;
      continue;
    }
    if (arg === '--dry-run') {
      apply = false;
      continue;
    }
    if (arg === '--from') {
      const value = args[index + 1];
      if (value === undefined || value.startsWith('--')) {
        throw new Error(`Missing value for ${arg}.`);
      }
      index += 1;
      fromScope = value;
      continue;
    }
    if (arg.startsWith('--')) {
      throw new Error(`Unknown argument "${arg}".`);
    }
    if (toScope !== undefined) {
      throw new Error(`Expected one target scope, got "${toScope}" and "${arg}".`);
    }
    toScope = arg;
  }

  if (toScope === undefined) {
    throw new Error(`Missing target scope.\n\n${usage()}`);
  }

  return { fromScope, toScope, apply };
}

function renderPlan(plan: ScopeRenamePlan): string {
  const total = plan.edits.reduce((sum, edit) => sum + edit.occurrences, 0);
  return [
    `Package-scope migration: ${plan.fromScope} -> ${plan.toScope}`,
    '',
    `Mode: ${plan.apply ? 'apply' : 'dry run (pass --apply to write changes)'}`,
    `Files: ${String(plan.edits.length)}  |  Token replacements: ${String(total)}`,
    '',
    ...(plan.edits.length === 0
      ? [`No ${plan.fromScope}/ tokens found. Nothing to migrate.`]
      : [
          'Files to patch:',
          ...plan.edits.map((edit) => `  ${edit.path} (${String(edit.occurrences)})`),
        ]),
    '',
    'After apply:',
    ...plan.postApply.map((item) => `  ${item}`),
  ].join('\n');
}

function renderApplyResult(plan: ScopeRenamePlan, result: ScopeRenameApplyResult): string {
  return [
    `Package-scope migration applied: ${plan.fromScope} -> ${plan.toScope}`,
    '',
    `Patched ${String(result.filesPatched.length)} files.`,
    '',
    'Next steps:',
    ...plan.postApply.map((item) => `  ${item}`),
    '  pnpm bslt gate merge',
  ].join('\n');
}

export function runScopeRenameCli(args: readonly string[] = [], root: string = REPO_ROOT): void {
  const options = parseScopeRenameArgs(args);
  const plan = planScopeRename({ ...options, root });

  if (!plan.apply) {
    console.log(renderPlan(plan));
    return;
  }

  const result = applyScopeRenamePlan(plan, root);
  console.log(renderApplyResult(plan, result));
}
