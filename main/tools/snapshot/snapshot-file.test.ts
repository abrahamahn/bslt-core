// main/tools/snapshot/snapshot-file.test.ts
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';

import { afterEach, describe, expect, it } from 'vitest';

import {
  checkSnapshot,
  compareText,
  diffLines,
  serializeSnapshot,
  snapshotHeader,
  writeSnapshot,
  type SnapshotSpec,
} from './snapshot-file';

const SPEC: SnapshotSpec = {
  id: 'api',
  file: 'api-surface.json',
  title: 'API surface',
  sources: 'the composed router',
};

const roots: string[] = [];

function tempRoot(): string {
  const root = mkdtempSync(path.join(tmpdir(), 'bslt-snapshot-'));
  roots.push(root);
  return root;
}

afterEach(() => {
  for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true });
});

describe('serializeSnapshot', () => {
  it('puts the header that names the command first, and ends with a newline', () => {
    const text = serializeSnapshot(SPEC, { routes: [{ path: '/a' }] });

    expect(text.endsWith('}\n')).toBe(true);
    const parsed = JSON.parse(text) as Record<string, unknown>;
    expect(Object.keys(parsed)).toEqual(['generated', 'routes']);
    expect(parsed['generated']).toBe(snapshotHeader(SPEC));
    expect(snapshotHeader(SPEC)).toBe(
      '@generated by `pnpm bslt snapshot api` from the composed router. Do not edit: run the command and commit the result.',
    );
  });

  it('is byte-identical for equal content', () => {
    expect(serializeSnapshot(SPEC, { a: [1, 2], b: { c: null } })).toBe(
      serializeSnapshot(SPEC, { a: [1, 2], b: { c: null } }),
    );
  });

  it('refuses a body that brings its own header', () => {
    expect(() => serializeSnapshot(SPEC, { generated: 'by hand' })).toThrow(/generated/u);
  });
});

describe('compareText', () => {
  it('orders by code unit, whatever the locale', () => {
    expect(['b', 'a', 'B', '_', 'ä', 'a1'].sort(compareText)).toEqual([
      'B',
      '_',
      'a',
      'a1',
      'b',
      'ä',
    ]);
  });
});

describe('diffLines', () => {
  it('is empty for equal text', () => {
    expect(diffLines('a\nb\n', 'a\nb\n')).toEqual([]);
  });

  it('marks removed and added lines with their line numbers', () => {
    const committed = ['{', '  "a": 1,', '  "b": 2,', '  "c": 3', '}', ''].join('\n');
    const current = ['{', '  "a": 1,', '  "b": 20,', '  "x": 0,', '  "c": 3', '}', ''].join('\n');

    expect(diffLines(committed, current)).toEqual([
      '@@ line 3 @@',
      '-   "b": 2,',
      '+   "b": 20,',
      '+   "x": 0,',
    ]);
  });

  it('reports separate hunks for separate changes', () => {
    const committed = ['a', 'b', 'c', 'd', 'e', 'f', 'g'].join('\n');
    const current = ['a', 'B', 'c', 'd', 'e', 'g'].join('\n');

    expect(diffLines(committed, current)).toEqual([
      '@@ line 2 @@',
      '- b',
      '+ B',
      '@@ line 6 @@',
      '- f',
    ]);
  });

  it('aligns separate hunks across catalog-sized spans (>4,000 unchanged middle lines)', () => {
    const middle = Array.from({ length: 5000 }, (_, index) => `line ${String(index)}`);
    const committed = ['top', 'old-fn', ...middle, 'old-table', 'bottom'].join('\n');
    const current = ['top', 'new-fn', ...middle, 'new-table', 'bottom'].join('\n');

    expect(diffLines(committed, current)).toEqual([
      '@@ line 2 @@',
      '- old-fn',
      '+ new-fn',
      '@@ line 5003 @@',
      '- old-table',
      '+ new-table',
    ]);
  });

  it('falls back without aligning when changed spans exceed the alignment cap', () => {
    const committed = Array.from({ length: 8500 }, (_, index) => `old ${String(index)}`).join('\n');
    const current = Array.from({ length: 8500 }, (_, index) => `new ${String(index)}`).join('\n');

    const lines = diffLines(committed, current, 5);

    expect(lines).toHaveLength(6);
    expect(lines[0]).toBe('@@ line 1 @@');
    expect(lines[1]).toBe('- old 0');
    expect(lines[5]).toBe('... 16996 more changed line(s)');
  });

  it('stops at the limit and says how much it left out', () => {
    const committed = Array.from({ length: 50 }, (_, index) => `old ${String(index)}`).join('\n');
    const current = Array.from({ length: 50 }, (_, index) => `new ${String(index)}`).join('\n');

    const lines = diffLines(committed, current, 10);

    expect(lines).toHaveLength(11);
    expect(lines.at(-1)).toBe('... 91 more changed line(s)');
  });
});

describe('writeSnapshot and checkSnapshot', () => {
  it('passes when the committed file equals the current content', () => {
    const root = tempRoot();
    const text = serializeSnapshot(SPEC, { routes: ['/a', '/b'] });

    expect(writeSnapshot(SPEC, text, root)).toBe(true);
    expect(readFileSync(path.join(root, SPEC.file), 'utf8')).toBe(text);
    expect(writeSnapshot(SPEC, text, root)).toBe(false);

    const result = checkSnapshot(SPEC, text, root);
    expect(result.ok).toBe(true);
    expect(result.summary).toContain('api-surface.json');
  });

  it('fails on a difference, shows it and says how to update on purpose', () => {
    const root = tempRoot();
    writeSnapshot(SPEC, serializeSnapshot(SPEC, { routes: ['/a', '/b'] }), root);

    const result = checkSnapshot(SPEC, serializeSnapshot(SPEC, { routes: ['/a', '/c'] }), root);

    expect(result.ok).toBe(false);
    expect(result.summary).toBe('API surface differs from api-surface.json');
    expect(result.problems).toContain('-     "/b"');
    expect(result.problems).toContain('+     "/c"');
    const hint = (result.problems ?? []).join('\n');
    expect(hint).toContain('pnpm bslt snapshot api');
    expect(hint).toContain('commit');
  });

  it('fails when the snapshot was never committed', () => {
    const result = checkSnapshot(SPEC, serializeSnapshot(SPEC, {}), tempRoot());

    expect(result.ok).toBe(false);
    expect(result.summary).toContain('api-surface.json does not exist');
    expect((result.problems ?? []).join('\n')).toContain('pnpm bslt snapshot api');
  });

  it('fails on a committed file that was edited by hand into another byte sequence', () => {
    const root = tempRoot();
    const text = serializeSnapshot(SPEC, { routes: ['/a'] });
    writeFileSync(path.join(root, SPEC.file), text.replace('\n', '\r\n'));

    expect(checkSnapshot(SPEC, text, root).ok).toBe(false);
  });
});
